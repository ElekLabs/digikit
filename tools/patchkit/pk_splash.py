#!/usr/bin/env python3
"""Boot splash image generator for ui/boot-splash: a 128x64 1-bit PNG -> the 1024-byte table `splash_bits`.

    uv run python -m tools.patchkit.pk_splash modules/ui/boot-splash/art/abigor-128x64.png \\
        -o modules/ui/boot-splash/src/cf/splash_bits.s [--polarity inverted|as-drawn] [--preview out/x.png]
    uv run python -m tools.patchkit.pk_splash --check modules/ui/boot-splash/src/cf/splash_bits.s

Layout (the firmware's Bitmap; setPixel 0x401124fc on DT2 1.17): column-major, two big-endian u32 words per column;
pixel (x, r) of the Bitmap is bit `0x80000000 >> (r & 31)` of word `2x + (r >> 5)`, so byte `8*x + k` holds Bitmap rows
`8k .. 8k+7` of column x with the MSB the lowest-numbered row; a set bit is a lit pixel. On the glass, Bitmap row r is
screen row `63 - r`: Bitmap row 0 is the bottom of the screen, x = 0 the left column. Evidence: the stock full-screen
intro image (the Bitmap the scene 0x400d11f0 blits) reads upright ("MORE IS MORE") only with that flip, and the UI
framebuffer reads upright under the emulator's panel model only with it (docs/findings/03-ui-and-panel.md, "The boot intro on DT2 1.17"; it corrects the
earlier "MSB = top row" reading). So the screen's top-left pixel is byte 7's LSB and its bottom-left
pixel byte 0's MSB. PNG row 0 is the top of the screen.

Polarity: `as-drawn` lights the PNG's white pixels (value >= 128); `inverted` lights its dark ones. The default is
`inverted` (the owner's choice for ui/boot-splash: a dark screen with the black-on-white art's figure lit). The
generated file records the source PNG (relative to the module) and the polarity in its header; `--check`
regenerates from them and fails when the committed table is stale.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

W, H = 128, 64
SIZE = W * H // 8
POLARITIES = ("inverted", "as-drawn")

Pixels = list[list[bool]]  # [y][x], True = lit


class SplashError(ValueError):
    pass


def encode(px: Pixels) -> bytes:
    if len(px) != H or any(len(row) != W for row in px):
        raise SplashError(f"need {W}x{H} pixels")
    out = bytearray(SIZE)
    for x in range(W):
        for y in range(H):
            if px[y][x]:
                r = H - 1 - y  # Bitmap row: 0 is the bottom of the screen
                out[8 * x + (r >> 3)] |= 0x80 >> (r & 7)
    return bytes(out)


def decode(data: bytes) -> Pixels:
    if len(data) != SIZE:
        raise SplashError(f"need {SIZE} bytes, got {len(data)}")
    rows = [
        [bool(data[8 * x + (r >> 3)] & (0x80 >> (r & 7))) for x in range(W)]
        for r in range(H)
    ]
    return rows[::-1]  # Bitmap row r is screen row 63 - r


def load_png(path: Path, invert: bool) -> Pixels:
    from PIL import Image

    with Image.open(path) as im:
        if im.size != (W, H):
            raise SplashError(f"{path}: {im.size[0]}x{im.size[1]}, need {W}x{H}")
        grey = im.convert("L").tobytes()  # one byte per pixel, row-major
        return [
            [(grey[y * W + x] >= 128) != invert for x in range(W)] for y in range(H)
        ]


def save_png(px: Pixels, path: Path, scale: int = 1) -> None:
    """Lit pixels white, dark pixels black (what the panel shows)."""
    from PIL import Image

    im = Image.new("1", (W, H))
    for y in range(H):
        for x in range(W):
            im.putpixel((x, y), 1 if px[y][x] else 0)
    if scale > 1:
        im = im.resize((W * scale, H * scale), Image.Resampling.NEAREST)
    im.save(path)


def to_asm(data: bytes, source: str, polarity: str) -> str:
    if len(data) != SIZE:
        raise SplashError(f"need {SIZE} bytes")
    if polarity not in POLARITIES:
        raise SplashError(f"polarity {polarity!r}")
    lines = [
        "| Generated by tools/patchkit/pk_splash.py; do not edit (modules/ui/boot-splash/README.md).",
        f"| source: {source}",
        f"| polarity: {polarity}",
        "| 1024 bytes, the firmware Bitmap layout: byte 8x+k = Bitmap rows 8k..8k+7 of column x (MSB first), 1 = lit;",
        "| Bitmap row r is screen row 63-r (byte 7 LSB = the screen's top-left pixel).",
        "",
        "    .section .rodata",
        "    .balign 4",
        "    .globl splash_bits",
        "splash_bits:",
    ]
    for i in range(0, SIZE, 16):
        words = [data[j : j + 4].hex() for j in range(i, i + 16, 4)]
        lines.append("    .long   " + ", ".join("0x" + w for w in words))
    lines += ["    .size   splash_bits, 1024", ""]
    return "\n".join(lines)


def parse_asm(text: str) -> tuple[bytes, str, str]:
    src = re.search(r"^\| source: (.+)$", text, re.M)
    pol = re.search(r"^\| polarity: (\S+)$", text, re.M)
    if not src or not pol:
        raise SplashError("no source/polarity header")
    data = b"".join(
        int(w, 16).to_bytes(4, "big")
        for line in re.findall(r"^\s*\.long\s+(.+)$", text, re.M)
        for w in line.split(",")
    )
    if len(data) != SIZE:
        raise SplashError(f"table has {len(data)} bytes")
    return data, src.group(1).strip(), pol.group(1)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("png", nargs="?", type=Path, help="128x64 PNG (threshold 128)")
    ap.add_argument("-o", "--out", type=Path, help="the .s to write")
    ap.add_argument("--polarity", choices=POLARITIES, default="inverted")
    ap.add_argument(
        "--preview", type=Path, help="also write what the panel shows (PNG, x4)"
    )
    ap.add_argument(
        "--check", type=Path, metavar="S", help="fail when this generated .s is stale"
    )
    a = ap.parse_args(argv)
    if a.check:
        data, source, polarity = parse_asm(a.check.read_text())
        png = a.check.resolve().parent.parent.parent / source
        want = encode(load_png(png, invert=polarity == "inverted"))
        if want != data:
            print(
                f"{a.check}: stale (source {source}, polarity {polarity})",
                file=sys.stderr,
            )
            return 1
        print(f"{a.check}: current (source {source}, polarity {polarity})")
        return 0
    if not a.png or not a.out:
        ap.error("need PNG and -o (or --check)")
    data = encode(load_png(a.png, invert=a.polarity == "inverted"))
    module = a.out.resolve().parent.parent.parent  # <module>/src/cf/x.s
    try:
        source = a.png.resolve().relative_to(module).as_posix()
    except ValueError:
        source = a.png.name
    a.out.write_text(to_asm(data, source, a.polarity))
    if a.preview:
        save_png(decode(data), a.preview, scale=4)
    lit = sum(bin(b).count("1") for b in data)
    print(f"{a.out}: {source}, {a.polarity}, {lit} of {W * H} pixels lit")
    return 0


if __name__ == "__main__":
    sys.exit(main())
