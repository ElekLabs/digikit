| ui/boot-splash on the Digitakt II (1.17): the boot intro's draw function.
|
| module.toml points the draw-function word of all five stock intro scene lists (anchor cf.intro.scenes) at this
| function and sets each frame count to 45. The stock intro task calls it once per 30 Hz frame, then flushes the
| bitmap to the OLED itself (docs/findings/03-ui-and-panel.md, "The boot intro on DT2 1.17").
|
|     void splash_draw(int frame, int nframes, Bitmap *bmp)
|
| Convention, read from the stock bytes (1.17): the caller 0x400d1992 pushes &bitmap, nframes, frame and does
| `jsr (a1)`, then pops 12 bytes and reloads d0/d1/a0 before using them. The stock draw functions read bmp at
| 12(sp) (0x400d11f0: `move.l 0x1c(a7)` after four pushes; 0x400d120c: `move.l 0x14(a7),d2` after saving d2/d3),
| clobber d0/d1/a0/a1 and save d2/d3 when they use them: cdecl, d0/d1/a0/a1 scratch, the rest preserved.
|
| Bitmap (ctor 0x401124b6, called by step() 0x400d1914 with w 128, h 64): +0 vtable, +4 width, +8 height,
| +0xc stride in u32 words per column = (h + 31) >> 5, +0x10 storage, +0x14 aux, +0x18 owns-storage flag byte.
| Pixel (x, r) is bit 0x80000000 >> (r & 31) of storage[x * stride + (r >> 5)] (setPixel 0x401124fc); 1 = lit.
| Bitmap row r is screen row 63 - r (row 0 is the bottom of the glass: the stock full-screen intro image reads
| upright only that way). splash_bits (splash_bits.s, generated by tools/patchkit/pk_splash.py, which does the flip)
| is in that layout, so the draw is a straight 256-word copy.
|
| Guard: copies only into a 128 x 64 Bitmap with stride 2 and non-NULL storage, never anything else, and writes
| only bmp->storage[0..255]. No firmware calls, no bss, uses d0/d1/a0/a1 only. Every frame is copied: the intro
| alternates two framebuffers; the stock diff flush sends nothing from the second frame on (the image is static).

    .text
    .globl splash_draw
splash_draw:
    movea.l 12(%sp),%a0         | bmp
    move.l  4(%a0),%d0
    cmpi.l  #128,%d0            | width
    bne.s   9f
    move.l  8(%a0),%d0
    moveq   #64,%d1
    cmp.l   %d1,%d0             | height
    bne.s   9f
    move.l  12(%a0),%d0
    moveq   #2,%d1
    cmp.l   %d1,%d0             | words per column
    bne.s   9f
    move.l  16(%a0),%d0         | storage
    beq.s   9f
    movea.l %d0,%a1
    lea     splash_bits,%a0
    move.l  #255,%d0
1:  move.l  (%a0)+,(%a1)+
    subq.l  #1,%d0
    bpl.s   1b                  | 256 words
9:  rts
