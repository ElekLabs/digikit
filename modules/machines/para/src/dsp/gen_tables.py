"""Constants and tables of the PARA machine (src/dsp/para.s); tools/patchkit/para_ref.py imports them.

    uv run python modules/machines/para/src/dsp/gen_tables.py   # writes tables.inc next to this file
"""

from __future__ import annotations

import math
import struct
import sys
from pathlib import Path

FS = 48000.0
FRAME = 2048  # Serum's frame size; a shorter sample is one frame of its own length
PAN_N = 256  # pan table steps, hard left to hard right
DETUNE_MAX = 256.0  # pitch words (256 per semitone) at full DTUN: 100 cents, cubed from the centre
OFF = 1e-4  # a decaying voice stops below this (-80 dB)


def attack_s(v: int) -> float:
    """ATK at knob value v: 0 is instant, then 1 ms to 4.1 s."""
    return 0.0 if v == 0 else 0.001 * 2 ** (v * 12 / 127)


def decay_s(v: int) -> float:
    """DEC at knob value v: the time to -60 dB, 5 ms to 10 s."""
    return 0.005 * 2 ** (v * 11 / 127)


def consts() -> list[tuple[str, float]]:
    return [
        ("ONE", 1.0),
        ("M1", -1.0),
        ("HALF", 0.5),
        ("NOTE0", 440.0 * 2 ** (-69 / 12)),
        ("SEMI", 1 / 3072),  # pitch word to octaves
        ("OCTMAX", 11.2),  # about 19 kHz
        ("INVFS", 1 / FS),
        ("W01", 1 / 0x7F00),
        ("DTN", 1 / 0x3F00),  # DTUN's word - 0x4000 to -1 .. 1
        ("DMAX", DETUNE_MAX),
        ("SPR", (PAN_N / 2) / 0x7F00),  # SPRD's word to pan steps either side of the centre
        ("GAIN", 1 / 2**31),  # each voice at half a single full-scale voice (0.707 per channel at the centre): headroom for four
        ("OFF", OFF),
    ]


def ainc() -> list[float]:
    """The attack's level step per sample for each knob value."""
    return [1.0 if v == 0 else 1 / (attack_s(v) * FS) for v in range(128)]


def dcoef() -> list[float]:
    """The decay's factor per sample for each knob value."""
    return [10 ** (-3 / (decay_s(v) * FS)) for v in range(128)]


def pan() -> list[float]:
    """Left gain at step q (0 hard left .. PAN_N hard right); the right gain is pan[PAN_N - q]."""
    return [math.cos(q / PAN_N * math.pi / 2) for q in range(PAN_N + 1)]


def _hex(vals: list[float]) -> str:
    return struct.pack(f"<{len(vals)}f", *vals).hex()


def emit() -> str:
    return "\n".join(
        [
            "// machines/para: generated by gen_tables.py; do not edit.",
            *[f"#define K_{name} {i}" for i, (name, _) in enumerate(consts())],
            f"#define FRAME {FRAME}",
            f"#define PAN_N {PAN_N}",
            f".PKHEX _pa_k, {_hex([v for _, v in consts()])};",
            f".PKHEX _pa_pan, {_hex(pan())};",
            f".PKHEX _pa_atk, {_hex(ainc())};",
            f".PKHEX _pa_dec, {_hex(dcoef())};",
            "",
        ]
    )


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("tables.inc")
    out.write_text(emit())
    print(f"wrote {out}")
