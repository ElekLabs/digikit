"""Constants and the pan table of the Chord machine (src/dsp/chord.s); tools/patchkit/chord_ref.py imports them.

    uv run python modules/machines/chord/src/dsp/gen_tables.py   # writes tables.inc next to this file
"""

from __future__ import annotations

import math
import struct
import sys
from pathlib import Path

PAN_N = 256  # pan table steps, hard left to hard right
DETUNE_MAX = 256.0  # pitch words (256 per semitone) at full DTUN: 100 cents, cubed from the centre
NOTE0 = 60 << 8  # the pitch word that plays the sample at its own pitch
# one voice at the centre plays the slot as loud as a stock sample machine (measured on the emulator: 5.15 dB over a sample read
# as int16 x 2^16, scaled by 2^-31, over the master's 10^0.5), divided by the centre's pan gain
G1 = 10 ** (5.15 / 20) / (32767.0 * 65536) / 10**0.5 / math.cos(math.pi / 4)


def consts() -> list[tuple[str, float]]:
    return [
        ("ONE", 1.0),
        ("M1", -1.0),
        ("HALF", 0.5),
        ("SEMI", 1 / 3072),  # pitch word to octaves
        ("OCTMAX", 5.0),
        ("LP", 1 / 0x3E00),  # LOOP's distance from the centre, past its first step, to 0 .. 1 of the sample
        ("DTN", 1 / 0x3F00),  # DTUN's word - 0x4000 to -1 .. 1
        ("DMAX", DETUNE_MAX),
        ("SPR", (PAN_N / 2) / 0x7F00),  # SPRD's word to pan steps either side of the centre
        ("G0", 0.0),
        *[(f"G{n}", G1 / math.sqrt(n)) for n in range(1, 5)],  # n voices: 1 / sqrt(n) each, as ChordWT
    ]


def pan() -> list[float]:
    """Left gain at step q (0 hard left .. PAN_N hard right); the right gain is pan[PAN_N - q]."""
    return [math.cos(q / PAN_N * math.pi / 2) for q in range(PAN_N + 1)]


def _hex(vals: list[float]) -> str:
    return struct.pack(f"<{len(vals)}f", *vals).hex()


def emit() -> str:
    return "\n".join(
        [
            "// machines/chord: generated by gen_tables.py; do not edit.",
            *[f"#define K_{name} {i}" for i, (name, _) in enumerate(consts())],
            f"#define PAN_N {PAN_N}",
            f"#define NOTE0 {NOTE0}",
            f".PKHEX _ch_k, {_hex([v for _, v in consts()])};",
            f".PKHEX _ch_pan, {_hex(pan())};",
            "",
        ]
    )


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("tables.inc")
    out.write_text(emit())
    print(f"wrote {out}")
