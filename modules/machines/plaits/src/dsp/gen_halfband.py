"""Generate halfband.h: Kaiser-windowed half-band FIR for the 48 -> 96 kHz stage.

Run from the repo root:
    uv run --with numpy python modules/machines/plaits/src/dsp/gen_halfband.py

Design: N = 4M+3 taps at 96 kHz, h[n] = sinc((n-C)/2) * kaiser(n, BETA), C=(N-1)/2.
Every second tap besides the centre is exactly zero, h[C] = 1 (zero-stuff gain
of 2 already folded in), so the odd output phase is a pure delay of M input
samples and the even phase is an (M+1)-pair symmetric MAC.
"""

from pathlib import Path

import numpy as np

M = 21  # N = 87 taps
BETA = 10.0  # Kaiser beta, ~100 dB stopband

N = 4 * M + 3
C = (N - 1) // 2
PAIRS = M + 1  # coefficients h[0], h[2], ..., h[2M]  (h[2M+1]=1 is the centre)
HIST = 2 * M + 2  # input history needed by the even phase
BUFSZ = 1
while BUFSZ < HIST:
    BUFSZ *= 2


def taps() -> np.ndarray:
    n = np.arange(N, dtype=np.float64)
    h = np.sinc((n - C) / 2.0) * np.kaiser(N, BETA)
    h[C] = 1.0
    return h


def main() -> None:
    h = taps()
    even = h[0::2]  # h[0], h[2], ..., h[N-1]
    coefs = ", ".join(f"{v:.9e}f" for v in even[:PAIRS])
    body = f"""/* GENERATED by gen_halfband.py - do not edit.
 * Half-band 2x interpolator, {N} taps at the 96 kHz rate, Kaiser beta={BETA}.
 * Group delay {C} samples at 96 kHz.
 */
#ifndef PLAITS_HALFBAND_H
#define PLAITS_HALFBAND_H

#define HB_PAIRS {PAIRS}
#define HB_ODD_DELAY {M}   /* odd phase = input delayed by this many samples */
#define HB_HIST {HIST}
#define HB_BUFSZ {BUFSZ}
#define HB_GROUP_DELAY {C} /* in 96 kHz samples */

/* h[2i] for i = 0..HB_PAIRS-1; h[2(HB_HIST-1-i)] mirrors it. */
static const float hb_coef[HB_PAIRS] = {{
    {coefs}
}};

typedef struct {{
    float buf[HB_BUFSZ];
    int pos; /* index of the next input write */
}} HalfBand;

void hb_init(HalfBand *s);
/* Writes 2*n48 samples; state carries across calls. */
void hb_up2(HalfBand *s, const float *in48, float *out96, int n48);

#endif
"""
    out = Path(__file__).with_name("halfband.h")
    out.write_text(body)
    print("wrote", out)


if __name__ == "__main__":
    main()
