"""Generate lib/terrain_memory.c and lib/terrain_memory.h: the memory next to two upstream tables that Plaits'
WaveTerrainEngine reads outside them (engines/terrain.c), as the host oracle build of upstream lays it out.

Upstream reads outside its tables in two places, neither guarded:
  - TerrainLookupWT indexes wav_integrated_waves at (bank * 64 + wave) * 132 + sample with wave = (x + 1) * 31.5 and
    sample = (y + 1) * 64; the path (x, y) of the FastSineOscillator leaves the unit square after parameter jumps
    (the magic circle is only renormalised when x^2 + y^2 leaves (0.5, 2)), so the index runs up to about 1,300 int16
    entries before the table and past its end (measured);
  - Sine (InterpolateWrap) reads lut_sine at (phase - trunc(phase)) * 512, which is negative for a negative phase: the
    AUX phase 1 + (y + z) / 4 goes negative when the path and the terrain are low, so up to 511 floats before lut_sine
    are read.
What those reads return is whatever the build placed there. The reference here is the oracle build that
tests/support/plaits_oracle.py makes from upstream's sources (its file order puts resources.cc before the LPC word
banks): before wav_integrated_waves lie lut_lpc_excitation_pulse and the waveshaper tables, after it the LPC word banks
(bank_0 ...), before lut_sine syx_bank_2. This script reads those bytes from the loaded oracle library and writes them
as the values upstream reads: int16 (little endian) as floats for the wave side, IEEE singles for the sine side.
tests/plaits/test_terrain_host.py checks the generated tables against the oracle's memory on every run.

    uv run python modules/machines/plaits/src/dsp/lib/gen_terrain_memory.py path/to/librun_oracle.so

(the library the oracle fixture builds: tests/support/plaits_oracle.py build(DIR) writes DIR/librun_oracle.so).
"""

from __future__ import annotations

import ctypes
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WAVES = "_ZN6plaits20wav_integrated_wavesE"
SINE = "_ZN6plaits8lut_sineE"
WAVE_ENTRIES = 25344
# entries modelled on each side of wav_integrated_waves (int16) and before lut_sine (float)
WAVE_APRON = 2048
SINE_APRON = 512


def memory(so: Path) -> dict[str, list[int]]:
    """The modelled regions as 32-bit words (float bit patterns), read from the loaded library."""
    lib = ctypes.CDLL(str(so))
    waves = ctypes.addressof(ctypes.c_int16.in_dll(lib, WAVES))
    sine = ctypes.addressof(ctypes.c_float.in_dll(lib, SINE))

    def i16_as_f32(addr: int, n: int) -> list[int]:
        vals = struct.unpack(f"<{n}h", ctypes.string_at(addr, 2 * n))
        return [int(struct.unpack("<I", struct.pack("<f", float(v)))[0]) for v in vals]

    return {
        "pl_terrain_wave_before": i16_as_f32(waves - 2 * WAVE_APRON, WAVE_APRON),
        "pl_terrain_wave_after": i16_as_f32(waves + 2 * WAVE_ENTRIES, WAVE_APRON),
        "pl_terrain_sine_before": list(
            struct.unpack(f"<{SINE_APRON}I", ctypes.string_at(sine - 4 * SINE_APRON, 4 * SINE_APRON))
        ),
    }


def main() -> None:
    so = Path(sys.argv[1])
    notice = (HERE / "tables.h").read_text().split("// ----")[0].rstrip() + "\n"
    head = [
        notice,
        "// -----------------------------------------------------------------------------",
        "//",
        "// GENERATED by lib/gen_terrain_memory.py from the host oracle build of upstream Plaits - do not edit.",
        "// The memory TERRAIN reads outside wav_integrated_waves and lut_sine (see the generator): IEEE single bit",
        "// patterns of the values upstream reads there.",
        "",
    ]
    regions = memory(so)
    h = [
        *head,
        "#ifndef PLAITS_LIB_TERRAIN_MEMORY_H",
        "#define PLAITS_LIB_TERRAIN_MEMORY_H",
        "",
        f"#define PL_TERRAIN_WAVE_APRON {WAVE_APRON}",
        f"#define PL_TERRAIN_SINE_APRON {SINE_APRON}",
        "/* entry k: wav_integrated_waves[k - PL_TERRAIN_WAVE_APRON] (before) and [25344 + k] (after) as floats */",
        f"extern const unsigned int pl_terrain_wave_before[{WAVE_APRON}];",
        f"extern const unsigned int pl_terrain_wave_after[{WAVE_APRON}];",
        "/* entry k: lut_sine[k - PL_TERRAIN_SINE_APRON] */",
        f"extern const unsigned int pl_terrain_sine_before[{SINE_APRON}];",
        "",
        "/* The bytes of these tables (selcc wants code in every unit it compiles for patchkit). */",
        "int pl_terrain_memory_bytes(void);",
        "",
        "#endif",
    ]
    c = [*head, '#include "terrain_memory.h"', ""]
    total = 0
    for name, words in regions.items():
        c.append(f"const unsigned int {name}[{len(words)}] = {{")
        for i in range(0, len(words), 4):
            c.append("  " + ", ".join(f"0x{w:08x}u" for w in words[i : i + 4]) + ",")
        c += ["};", ""]
        total += 4 * len(words)
    c += [f"int pl_terrain_memory_bytes(void) {{ return {total}; }}", ""]
    (HERE / "terrain_memory.h").write_text("\n".join(h) + "\n")
    (HERE / "terrain_memory.c").write_text("\n".join(c))


if __name__ == "__main__":
    main()
