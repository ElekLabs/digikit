//! The platform under the core (docs/ARCHITECTURE.md, layer L1): everything the core asks of the device and the firmware: who the device is, the
//! block clock, interrupt mask, cache flush, the card's block calls, MIDI output, the OS upgrade flag, soft reset, the task kernel, and the optional
//! providers (the sample pool, the staged writer).
//!
//! `RealPlatform` (runtime crate, `platform.rs`) is a zero-sized type over the firmware calls of the `dkfw` crate and the device object's words, so a
//! call through it costs what the direct call cost. A core function that a host test drives takes a generic `P: Platform` (no `dyn`: the runtime has no
//! allocator and no vtables); everything else calls the `PLATFORM` constant. `FakePlatform` (host tests of the runtime crate) models a card, a clock,
//! the mask, MIDI output and the providers.
//!
//! What stays out: `st()` (core state) and the pure helpers `rd32`, `wr32`, `cstr_*` (`mem`). The firmware calls of one service (the machines
//! service's page, input and parameter calls) go behind that service's own interface (`paramapi::Fw`), not into this trait.
//!
//! Every fact that differs between devices is data of the device files: `DeviceProfile` (generated, `profiles.rs`) and never a comparison of the
//! device id in code.
use core::ffi::c_void;

/// What a device file says about the device, as the runtime branches on it. `RealPlatform` reads these words from the device object (`device.s`,
/// generated by `patchkit gen`); `profiles.rs` holds one constant per device file from the same facts.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DeviceProfile {
    /// `[digikit] id`.
    pub id: u32,
    /// `[digikit] name`: up to 3 characters and a NUL, as a big-endian word.
    pub name: u32,
    /// `[capabilities] card = "slots"`: the samples are files of the digikit store (`samples/` folder). Otherwise they live in the firmware's folder
    /// filesystem (`card = "path-fs"`).
    pub samples_in_store: bool,
    /// `[digikit] sample_path_max`: the longest sample path (bytes, relative to the samples root) a transfer or a `select` may name.
    pub sample_path_max: u32,
}

/// The firmware's task kernel and its heap.
pub trait Tasking {
    /// A semaphore is 8 bytes: a count or flag and the one waiting TCB. No static initialiser.
    unsafe fn sem_init(&self, sem: *mut u32, count: u32);
    unsafe fn sem_pend(&self, sem: *mut u32);
    /// Sets the flag and reschedules. ISR-safe.
    unsafe fn sem_post(&self, sem: *mut u32);
    /// Sleep `us` microseconds (task context).
    unsafe fn sleep_us(&self, us: u32);
    /// Create a task on `tcb` and `stack`; `true` when the kernel accepted it. It starts with `task_start`.
    unsafe fn task_create(
        &self,
        tcb: u32,
        entry: u32,
        priority: u32,
        stack: u32,
        stack_bytes: u32,
    ) -> bool;
    unsafe fn task_start(&self, tcb: u32);
    /// The current task's TCB address.
    unsafe fn current_task(&self) -> u32;
    /// The firmware's heap: null when it is out of memory.
    unsafe fn alloc(&self, bytes: u32) -> *mut u8;
    unsafe fn free(&self, p: *mut u8);
}

/// Optional provider: the firmware's sample worker and the sample-pool adapter behind it. Calls are valid only when `present()`.
pub trait SamplePool {
    /// Is a sample-pool adapter of the right version in the image?
    fn present(&self) -> bool;
    /// The firmware's sample worker object; 0 when it does not exist yet.
    unsafe fn worker(&self) -> u32;
    /// Queue a job on the worker (`job` and `done` are its two 32-byte function and flag tables).
    unsafe fn worker_queue(
        &self,
        worker: u32,
        name: *const u8,
        job: *mut c_void,
        done: *mut c_void,
    );
}

/// Optional provider: the staged writer of the +Drive filesystem (`dkpw_*`). Its calls stay with the store writer; this says whether they may be made.
pub trait StagedWriter {
    /// Is a staged-writer adapter of the right version in the image?
    fn present(&self) -> bool;
}

pub trait Platform: Tasking + SamplePool + StagedWriter {
    // ---- who the device is -----------------------------------------------------------------------------------------------
    fn profile(&self) -> DeviceProfile;
    /// The 8-byte id of this image as patchkit stamped it (zeros in an unpatched object).
    fn image_id(&self) -> [u8; 8];

    // ---- timing and interrupts -------------------------------------------------------------------------------------------
    /// The firmware's DSP block counter (about 1500 per second from boot; it wraps); `None` when it is not available.
    fn blocks(&self) -> Option<u32>;
    /// Mask interrupts; the old status register.
    fn irq_mask(&self) -> u32;
    fn irq_restore(&self, sr: u32);
    /// Write back and invalidate both caches over a byte range (before running fresh code).
    fn flush(&self, start: u32, len: u32);

    // ---- the card --------------------------------------------------------------------------------------------------------
    /// Read `bytes` (a multiple of 512) from `sector` into `buf`; 0 or a negative error.
    unsafe fn block_read(&self, sector: u32, bytes: u32, buf: *mut u8) -> i32;
    /// The firmware's block write, ungated. Only the one gated write (`platform::block_write`) and the card claim call it.
    unsafe fn block_write_raw(&self, sector: u32, bytes: u32, buf: *const u8) -> i32;

    // ---- MIDI and the firmware's state ------------------------------------------------------------------------------------
    /// Send one complete MIDI message (F0 .. F7 for SysEx) to `port` (2 = USB).
    unsafe fn midi_send(&self, port: u32, msg: &[u8]);
    /// Bytes handed to the USB stack for MIDI and not yet sent (0 when drained); `None` when it is not available.
    fn midi_tx_in_flight(&self) -> Option<u32>;
    /// An OS upgrade stream is being taken.
    fn os_upgrade_active(&self) -> bool;
    /// The machine type of `track` of the active kit, read-only: `None` when there is no project yet, `Some(-1)` past track 15 or when the firmware has no
    /// type for the track.
    unsafe fn track_type(&self, track: u32) -> Option<i32>;
    /// Is panel key `key` held?
    unsafe fn key_down(&self, key: u32) -> bool;
    fn soft_reset(&self) -> !;
    /// Point the firmware's exception handler at the runtime's hook (`dkrt_exc`, through the adapter's trampoline). `true` when this call changed it. The runtime
    /// asks every UI pass: the firmware sets its own hook word in its boot, so the first successful call comes after that.
    fn install_exception_hook(&self) -> bool;

    // ---- provided: the profile's facts -------------------------------------------------------------------------------------
    fn device_id(&self) -> u32 {
        self.profile().id
    }
    fn device_name(&self) -> u32 {
        self.profile().name
    }
    /// The samples are files of the digikit store, not the firmware's folder filesystem.
    fn samples_in_store(&self) -> bool {
        self.profile().samples_in_store
    }
    fn sample_path_max(&self) -> u32 {
        self.profile().sample_path_max
    }
}

/// Blocks from `start` to now, wrapping; `None` when the clock was or is not available.
pub fn blocks_since<P: Platform>(p: &P, start: Option<u32>) -> Option<u32> {
    match (start, p.blocks()) {
        (Some(a), Some(b)) => Some(b.wrapping_sub(a)),
        _ => None,
    }
}

/// Run `f` with interrupts masked, restoring the status register of the caller (nesting-safe).
pub fn locked<P: Platform, T>(p: &P, f: impl FnOnce() -> T) -> T {
    let sr = p.irq_mask();
    let r = f();
    p.irq_restore(sr);
    r
}
