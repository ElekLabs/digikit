    IF NE JUMP _lp_cb_bad;
    R5 = PASS R5;
    IF LT JUMP _lp_cb_bad;
    R0 = 235;
    COMP(R5, R0);
    IF GE JUMP _lp_cb_bad;
    // Validate byte progress before deriving any destination. No input ranges.
    R6 = DM(_lp_bytes);
    R1 = LSHIFT R5 BY 12;
    COMP(R6, R1);
    IF NE JUMP _lp_cb_bad;
    R0 = 960000;
    R0 = R0 - R6;
    R1 = 4096;
    R7 = MIN(R0, R1);
    R0 = 0x10200000;
    R1 = LSHIFT R6 BY -2;
    R0 = R0 + R1;
    I1 = R0;
    MODIFY(I0, 4);
    R0 = LSHIFT R7 BY -2;
