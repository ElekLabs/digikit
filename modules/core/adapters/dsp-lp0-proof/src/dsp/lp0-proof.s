    I1 = 0x1023a980;
    R3 = 0xa55a3cc3;
    R5 = 1024;
_lp_guard_check:
    R0 = DM(I0, M6) (NW);
    COMP(R0, R3);
    IF NE JUMP _lp_cb_bad;
