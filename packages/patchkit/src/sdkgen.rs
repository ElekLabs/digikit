/// One `code: (name, text),` line of a Python status table (expanded when it is wider than `PY_WIDTH`).
fn py_status(s: &mut String, name: &str, st: &Status) {
    let one = format!("    {}: ({name:?}, {:?}),", st.code, st.text);
    if one.chars().count() <= PY_WIDTH {
        s.push_str(&one);
        s.push('\n');
    } else {
        let _ = writeln!(
            s,
            "    {}: (\n        {name:?},\n        {:?},\n    ),",
            st.code, st.text
        );
    }
}

/// `tools/device/dkproto.py`: the protocol numbers and the status texts.
fn python_proto(sdk: &Sdk) -> String {
    let p = &sdk.protocol;
    let mut s = format!("# {HEADER}\n\n");
    let _ = writeln!(s, "VERSION = {}", p.version);
    for (n, v) in p.limits.all() {
        let _ = writeln!(s, "{n} = {v}");
    }
    s.push_str("\n# the .dkm loader's format limits ([limits.format])\n");
    for (n, v) in format_limits(sdk) {
        let _ = writeln!(s, "{n} = {v}");
    }
    s.push('\n');
    s.push_str("# the record kinds of a .dkm ([records.kinds])\nRECORD_KIND: dict[str, int] = {\n");
    let mut kinds: Vec<_> = sdk.records.kinds.iter().collect();
    kinds.sort_by_key(|(_, k)| k.id);
    for (n, k) in &kinds {
        let _ = writeln!(s, "    {n:?}: {},", k.id);
    }
    s.push_str("}\n\n");
    s.push_str("CMD: dict[str, int] = {\n");
    for (n, v) in by_value(&p.commands) {
        let _ = writeln!(s, "    {n:?}: 0x{v:02X},");
    }
    s.push_str("}\n");
    for (n, v) in by_value(&p.commands) {
        let _ = writeln!(s, "CMD_{n} = 0x{v:02X}");
    }
    s.push_str("\nSERVICE_CMD: dict[str, int] = {\n");
    for (n, v) in by_value(&p.service) {
        let _ = writeln!(s, "    {n:?}: 0x{v:02X},");
    }
    s.push_str("}\n");
    s.push_str("\nSTATUS: dict[int, tuple[str, str]] = {\n");
    for (n, st) in by_code(&p.status) {
        py_status(&mut s, n, st);
    }
    s.push_str("}\n\nLOAD_STATUS: dict[int, tuple[str, str]] = {\n");
    for (n, st) in by_code(&sdk.load.status) {
        py_status(&mut s, n, st);
    }
    s.push_str("}\n\nCAP: dict[str, int] = {\n");
    for (n, bit) in by_value(&p.caps) {
        let _ = writeln!(s, "    {n:?}: {bit},");
    }
    s.push_str("}\n\nRANGES: dict[str, tuple[int, int]] = {\n");
    for (n, [first, last]) in &p.ranges {
        let _ = writeln!(s, "    {n:?}: (0x{first:02X}, 0x{last:02X}),");
    }
    s.push_str("}\n");
    s.push_str("\nCAPACITY_KINDS: dict[str, int] = {\n");
    for (n, k) in by_value(&kind_ids(sdk)) {
        let _ = writeln!(s, "    {n:?}: {k},");
    }
    let st = &sdk.settings;
    let _ = write!(
        s,
        "}}\n\nSETTINGS_SECTORS = {}  # one copy of the settings record\nSETTINGS_COPIES = {}\nSETTINGS_KEY_MAX = {}\nSETTINGS_VALUE_MAX = {}\n",
        st.sectors, st.copies, st.key_max, st.value_max
    );
    s.push_str("\n# (prefix, how a host reader decodes the value)\nSETTINGS_KEYS: tuple[tuple[str, str], ...] = (\n");
    for k in &st.key {
        let _ = writeln!(s, "    ({:?}, {:?}),", k.prefix, k.value);
    }
    s.push_str(")\n");
    s
}

