const BASES: [&str; 10] = [
    "u8", "u16", "u32", "i8", "i16", "i32", "bool", "void", "char", "float",
];
/// The import name field of the runtime's table is 32 bytes (as in the .dkm), NUL-terminated.
const IMPORT_NAME_MAX: usize = 31;

/// A type of a signature: `const`, a base, the number of `*`; `td` marks a name of `[handle.callbacks]` (a function type).
#[derive(Clone)]
pub(crate) struct Ty {
    pub(crate) is_const: bool,
    pub(crate) base: String,
    pub(crate) ptr: usize,
    pub(crate) td: bool,
}

pub(crate) struct Sig {
    pub(crate) ret: Ty,
    pub(crate) args: Vec<(Ty, String)>,
}

/// A field of a typed struct view: type, name, doc.
struct CField(Ty, String, String);

/// The typed view of a contract: the two structs and the entry points (name, signature, doc).
struct View {
    input: Vec<CField>,
    desc: Vec<CField>,
    fns: Vec<(String, Sig, String)>,
}

pub(crate) fn is_ident(s: &str) -> bool {
    !s.is_empty()
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !s.starts_with(|c: char| c.is_ascii_digit())
}

/// `u8 *out` -> (`u8 *`, `out`); the name is empty when the text ends in `*` or a space-free type.
fn split_name(s: &str) -> (&str, &str) {
    let s = s.trim();
    let i = s
        .char_indices()
        .rev()
        .find(|(_, c)| !(c.is_ascii_alphanumeric() || *c == '_'))
        .map_or(0, |(i, c)| i + c.len_utf8());
    (s[..i].trim(), &s[i..])
}

fn parse_ty(what: &str, s: &str, types: &BTreeMap<String, String>, extra: &[&str]) -> Result<Ty> {
    let ptr = s.matches('*').count();
    let words: Vec<&str> = s
        .split(|c: char| c == '*' || c.is_whitespace())
        .filter(|w| !w.is_empty())
        .collect();
    let (is_const, base) = match words.as_slice() {
        ["const", b] => (true, *b),
        [b] => (false, *b),
        _ => return Err(err!("{SOURCE}: {what}: bad type {s:?}")),
    };
    let td = types.contains_key(base);
    if !(td || BASES.contains(&base) || extra.contains(&base)) {
        return Err(err!("{SOURCE}: {what}: unknown type {base:?}"));
    }
    Ok(Ty {
        is_const,
        base: base.to_string(),
        ptr,
        td,
    })
}

/// A signature `<ret> [name](<type> <name>, ...)`: the name of the function when there is one.
pub(crate) fn parse_fn(
    what: &str,
    s: &str,
    types: &BTreeMap<String, String>,
    extra: &[&str],
) -> Result<(Option<String>, Sig)> {
    let (Some(open), true) = (s.find('('), s.trim_end().ends_with(')')) else {
        return Err(err!("{SOURCE}: {what}: {s:?} is not a signature"));
    };
    let head = s[..open].trim();
    let inner = s.trim_end();
    let inner = &inner[open + 1..inner.len() - 1];
    let (t, n) = split_name(head);
    let type_word =
        |w: &str| w == "const" || BASES.contains(&w) || types.contains_key(w) || extra.contains(&w);
    let (rt, name) = if !n.is_empty() && !type_word(n) {
        (t, Some(n.to_string()))
    } else {
        (head, None)
    };
    let ret = parse_ty(what, rt, types, extra)?;
    let mut args = Vec::new();
    if !inner.trim().is_empty() {
        for a in inner.split(',') {
            let (t, n) = split_name(a);
            if t.is_empty() || !is_ident(n) {
                return Err(err!(
                    "{SOURCE}: {what}: argument {a:?} needs a type and a name"
                ));
            }
            args.push((parse_ty(what, t, types, extra)?, n.to_string()));
        }
    }
    Ok((name, Sig { ret, args }))
}

fn camel(s: &str) -> String {
    s.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| p[..1].to_uppercase() + &p[1..])
        .collect()
}

fn rust_ty(t: &Ty) -> String {
    let base = match t.base.as_str() {
        "u8" | "char" => "u8".to_string(),
        "void" if t.ptr > 0 => "u8".to_string(),
        "void" => "()".to_string(),
        "bool" => "bool".to_string(),
        "float" => "f32".to_string(),
        b if t.ptr > 0 && b.starts_with("dk_") => "u8".to_string(),
        b if t.td => {
            if t.ptr == 0 {
                return format!("Option<{}>", camel(b));
            }
            camel(b)
        }
        b => b.to_string(),
    };
    let mut s = base;
    for i in 0..t.ptr {
        s = format!(
            "*{} {s}",
            if i == 0 && t.is_const { "const" } else { "mut" }
        );
    }
    s
}

/// A parameter name as Rust text: `fn` is a keyword there.
fn rust_name(n: &str) -> String {
    if n == "fn" {
        "r#fn".to_string()
    } else {
        n.to_string()
    }
}

/// `unsafe extern "C" fn(a: u32) -> i32` (the result is left out for `void`).
pub(crate) fn rust_fn(sig: &Sig) -> String {
    let args: Vec<String> = sig
        .args
        .iter()
        .map(|(t, n)| format!("{}: {}", rust_name(n), rust_ty(t)))
        .collect();
    let ret = if sig.ret.base == "void" && sig.ret.ptr == 0 {
        String::new()
    } else {
        format!(" -> {}", rust_ty(&sig.ret))
    };
    format!("unsafe extern \"C\" fn({}){ret}", args.join(", "))
}

fn c_ty(t: &Ty) -> String {
    let base = match t.base.as_str() {
        "u8" => "uint8_t".to_string(),
        "u16" => "uint16_t".to_string(),
        "u32" => "uint32_t".to_string(),
        "i8" => "int8_t".to_string(),
        "i16" => "int16_t".to_string(),
        "i32" => "int32_t".to_string(),
        "bool" => "_Bool".to_string(),
        b if t.td => format!("dk_{b}"),
        b => b.to_string(),
    };
    let ptr = t.ptr + usize::from(t.td);
    let mut s = String::new();
    if t.is_const {
        s.push_str("const ");
    }
    s.push_str(&base);
    if ptr > 0 {
        s.push(' ');
        s.push_str(&"*".repeat(ptr));
    }
    s
}

/// A C declaration of `name` with type `t` (the `*` binds to the name).
pub(crate) fn c_decl(t: &Ty, name: &str) -> String {
    let s = c_ty(t);
    if s.ends_with('*') {
        format!("{s}{name}")
    } else {
        format!("{s} {name}")
    }
}

pub(crate) fn c_args(sig: &Sig) -> String {
    if sig.args.is_empty() {
        return "void".to_string();
    }
    let a: Vec<String> = sig.args.iter().map(|(t, n)| c_decl(t, n)).collect();
    a.join(", ")
}

/// The `[handle.callbacks]`: (name, signature). Their names end in `_fn`.
fn callback_types(sdk: &Sdk) -> Result<Vec<(&String, Sig)>> {
    let none = BTreeMap::new();
    let handles: Vec<&str> = sdk.handle.types.iter().map(String::as_str).collect();
    let mut v = Vec::new();
    for (n, s) in &sdk.handle.callbacks {
        let what = format!("[handle.callbacks] {n}");
        let (name, sig) = parse_fn(&what, s, &none, &handles)?;
        if name.is_some() || !is_ident(n) || !n.ends_with("_fn") || BASES.contains(&n.as_str()) {
            return Err(err!(
                "{SOURCE}: {what}: bad name (it ends in _fn) or signature"
            ));
        }
        v.push((n, sig));
    }
    Ok(v)
}

/// The imports with their signatures, checked.
fn imports(sdk: &Sdk) -> Result<Vec<(&Import, Option<Sig>)>> {
    let mut v = Vec::new();
    let handles: Vec<&str> = sdk.handle.types.iter().map(String::as_str).collect();
    callback_types(sdk)?;
    let types: BTreeMap<String, String> = sdk.handle.callbacks.clone();
    for h in &sdk.handle.types {
        if !is_ident(h) || !h.starts_with("dk_") || BASES.contains(&h.as_str()) {
            return Err(err!("{SOURCE}: [handle] types: {h:?} is not a dk_ name"));
        }
    }
    for (i, im) in sdk.import.iter().enumerate() {
        let what = format!("[[import]] {}", im.name);
        if !is_ident(&im.name)
            || im.name.len() > IMPORT_NAME_MAX
            || sdk.import[..i].iter().any(|o| o.name == im.name)
        {
            return Err(err!(
                "{SOURCE}: {what}: bad name, over {IMPORT_NAME_MAX} bytes, or twice"
            ));
        }
        if im.doc.is_empty() || im.doc.contains("*/") {
            return Err(err!("{SOURCE}: {what}: needs a doc without a comment end"));
        }
        if !matches!(im.kind.as_deref(), None | Some("helper")) {
            return Err(err!("{SOURCE}: {what}: kind is helper"));
        }
        let sig = match &im.sig {
            Some(s) => {
                let (name, sig) = parse_fn(&what, s, &types, &handles)?;
                if name.is_some() {
                    return Err(err!("{SOURCE}: {what}: a signature has no function name"));
                }
                Some(sig)
            }
            None if im.kind.as_deref() == Some("helper") => None,
            None => return Err(err!("{SOURCE}: {what}: needs a sig")),
        };
        if let Some(a) = &im.absent {
            let Some(sig) = &sig else {
                return Err(err!("{SOURCE}: {what}: absent needs a sig"));
            };
            if im.requires.is_none() {
                return Err(err!("{SOURCE}: {what}: absent needs requires"));
            }
            let is_void = sig.ret.base == "void" && sig.ret.ptr == 0;
            let ok = if is_void {
                a == "void"
            } else if a == "missing" {
                sig.ret.base == "i32" && sig.ret.ptr == 0
            } else {
                a.parse::<i32>().is_ok()
            };
            if !ok {
                return Err(err!(
                    "{SOURCE}: {what}: absent {a:?} does not fit the return type (\"void\" for void, \"missing\" for i32, else a number)"
                ));
            }
        }
        match (&im.service, &im.since, &im.context) {
            (None, None, None) if im.kind.as_deref() == Some("helper") => {}
            (Some(svc), Some(since), Some(ctx)) => {
                if !sdk.handle.services.contains(svc) {
                    return Err(err!("{SOURCE}: {what}: unknown service {svc:?}"));
                }
                if !sdk.handle.contexts.contains(ctx) {
                    return Err(err!("{SOURCE}: {what}: unknown context {ctx:?}"));
                }
                let v = parse_runtime(since)
                    .map_err(|e| err!("{SOURCE}: {what}: since {since:?}: {e}"))?;
                if v == 0 || v > pack_runtime(runtime_parts(sdk)?) {
                    return Err(err!(
                        "{SOURCE}: {what}: since {since:?} is not in 0.0.1 ..= [runtime] version"
                    ));
                }
                if sig.is_none() {
                    return Err(err!("{SOURCE}: {what}: a service import needs a sig"));
                }
            }
            _ => {
                return Err(err!(
                    "{SOURCE}: {what}: service, since and context are set together"
                ));
            }
        }
        v.push((im, sig));
    }
    Ok(v)
}

/// What the packer needs of a service import (`[[import]]` with `service`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ImportInfo {
    pub service: String,
    /// The import has a stub for an absent provider (`absent`): a module may load without it.
    pub optional: bool,
    /// The runtime version that added it, packed major << 16 | minor << 8 | patch.
    pub since: u32,
    pub context: String,
}

/// `service`, `since` and `context` of every import that has them (`[[import]]` with `service`) in the `sdk/sdk.toml` this crate was built with, by name.
/// A compiler helper (`memcpy`, ...) has none and is not in the map.
pub fn import_infos() -> BTreeMap<String, ImportInfo> {
    sdk_embedded()
        .import
        .iter()
        .filter_map(|i| match (&i.service, &i.since, &i.context) {
            (Some(s), Some(since), Some(c)) => Some((
                i.name.clone(),
                ImportInfo {
                    service: s.clone(),
                    optional: i.absent.is_some(),
                    since: parse_runtime(since).expect("parse checked since"),
                    context: c.clone(),
                },
            )),
            _ => None,
        })
        .collect()
}

fn sdk_embedded() -> Sdk {
    parse(include_str!("../../../sdk/sdk.toml")).expect("sdk/sdk.toml parses")
}

fn c_field(what: &str, entry: &str) -> Result<CField> {
    let (decl, doc) = entry.split_once(" // ").unwrap_or((entry, ""));
    let (t, n) = split_name(decl);
    if t.is_empty() || !is_ident(n) {
        return Err(err!("{SOURCE}: {what}: {entry:?} needs a type and a name"));
    }
    let ty = parse_ty(what, t, &BTreeMap::new(), &[])?;
    if !(ty.ptr > 0 || ["u32", "i32", "float"].contains(&ty.base.as_str())) {
        return Err(err!("{SOURCE}: {what}: {n} is not 4 bytes"));
    }
    Ok(CField(ty, n.to_string(), doc.to_string()))
}

/// A typed view `[machine.c]` / `[fx.c]`: the field names must equal the contract's name lists in order.
fn c_view(
    what: &str,
    c: &CView,
    input_names: &[String],
    desc_names: &[String],
    extra: &[&str],
) -> Result<View> {
    let fields = |kind: &str, list: &[String], names: &[String]| -> Result<Vec<CField>> {
        let what = format!("{what} {kind}");
        let v = list
            .iter()
            .map(|e| c_field(&what, e))
            .collect::<Result<Vec<_>>>()?;
        let got: Vec<&str> = v.iter().map(|f| f.1.as_str()).collect();
        let want: Vec<&str> = names.iter().map(String::as_str).collect();
        if got != want {
            return Err(err!(
                "{SOURCE}: {what}: the names {got:?} are not the name list {want:?}"
            ));
        }
        Ok(v)
    };
    let input = fields("input", &c.input, input_names)?;
    let desc = fields("desc", &c.desc, desc_names)?;
    let mut fns = Vec::new();
    for e in &c.fns {
        let (decl, doc) = e.split_once(" // ").unwrap_or((e, ""));
        let (name, sig) = parse_fn(&format!("{what} fns"), decl, &BTreeMap::new(), extra)?;
        let name = name.ok_or_else(|| err!("{SOURCE}: {what} fns: {e:?} needs a function name"))?;
        fns.push((name, sig, doc.to_string()));
    }
    Ok(View { input, desc, fns })
}

fn machine_view(sdk: &Sdk) -> Result<View> {
    let m = &sdk.machine;
    c_view("[machine.c]", &m.c, &m.voice_in, &m.desc, &["dk_voice_in"])
}

fn fx_view(sdk: &Sdk) -> Result<View> {
    let m = &sdk.fx;
    c_view("[fx.c]", &m.c, &m.fx_in, &m.desc, &["dk_fx_in"])
}

/// Everything that `render` reads from the tables of this part, checked once at the parse.
fn check_views(sdk: &Sdk) -> Result<()> {
    imports(sdk)?;
    machine_view(sdk)?;
    fx_view(sdk)?;
    Ok(())
}

/// The `pub mod api` of `gen_sdk.rs`: the callback types of the imports, the import names and their function types.
fn rust_api(sdk: &Sdk) -> Result<String> {
    let mut s = String::from(
        "/// The imports of a module (`[[import]]`) and the callback types they take (`[handle.callbacks]`).\npub mod api {\n",
    );
    for (n, sig) in callback_types(sdk)? {
        let _ = writeln!(
            s,
            "    /// The callback type `{n}` of `[handle.callbacks]`."
        );
        let _ = writeln!(s, "    pub type {} = {};\n", camel(n), rust_fn(&sig));
    }
    let imps = imports(sdk)?;
    s.push_str("    /// The names a module may import, in the order of the runtime's table (`[[import]]`).\n");
    let _ = writeln!(s, "    pub const IMPORT_NAMES: [&str; {}] = [", imps.len());
    for (im, _) in &imps {
        let _ = writeln!(s, "        {:?},", im.name);
    }
    s.push_str("    ];\n");
    let own: Vec<_> = imps
        .iter()
        .filter(|(im, _)| im.requires.is_none())
        .collect();
    s.push_str("\n    /// The names the runtime's own table holds (`IMPORTS`), in order: the imports without `requires`.\n");
    let _ = writeln!(s, "    pub const BUILTIN_NAMES: [&str; {}] = [", own.len());
    for (im, _) in &own {
        let _ = writeln!(s, "        {:?},", im.name);
    }
    s.push_str("    ];\n");
    for (im, sig) in &imps {
        let (None, Some(sig)) = (&im.kind, sig) else {
            continue;
        };
        let _ = writeln!(s, "\n    /// `{}`: {}", im.name, im.doc);
        let _ = writeln!(s, "    pub type {}Fn = {};", camel(&im.name), rust_fn(sig));
    }
    s.push_str("}\n");
    let missing = sdk
        .load
        .status
        .get("E_MISSING")
        .map(|m| m.code)
        .ok_or_else(|| err!("{SOURCE}: [load.status] has no E_MISSING"))?;
    s.push_str(&rust_optional(&imps, missing));
    Ok(s)
}

/// The macro `optional_imports!` for the runtime crate: the imports that another module provides (`requires`). It declares each as an external
/// function (patchkit links an `[object] optional` symbol to 0 when its module is not in the image), the stub of each that has `absent`, and
/// `optional::table()`: per import its name, the address the module gave (0 when absent), the address of the stub (0 when it has none) and the module that provides it. It is
/// a macro because the undefined symbols must belong to the runtime's own object, not to this crate.
fn rust_optional(imps: &[(&Import, Option<Sig>)], missing: i32) -> String {
    let opt: Vec<_> = imps
        .iter()
        .filter(|(im, _)| im.requires.is_some())
        .collect();
    let mut s = String::from(
        "\n/// The imports that another module provides (`[[import]] requires`): the external functions, the stubs for an absent module and\n/// the table of both. Expand it once in the runtime's object; its symbols must be in the `optional` list of the runtime's module.toml.\n#[macro_export]\nmacro_rules! optional_imports {\n    () => {\n        #[allow(dead_code, trivial_numeric_casts)]\n        pub mod optional {\n            #[allow(unused_imports)]\n            use $crate::api::*;\n            extern \"C\" {\n",
    );
    let decl = |sig: &Sig, keep: bool| -> String {
        sig.args
            .iter()
            .enumerate()
            .map(|(i, (t, n))| {
                if keep {
                    format!("{}: {}", rust_name(n), rust_ty(t))
                } else {
                    format!("_a{i}: {}", rust_ty(t))
                }
            })
            .collect::<Vec<_>>()
            .join(", ")
    };
    let ret = |sig: &Sig| -> String {
        if sig.ret.base == "void" && sig.ret.ptr == 0 {
            String::new()
        } else {
            format!(" -> {}", rust_ty(&sig.ret))
        }
    };
    for (im, sig) in &opt {
        let sig = sig.as_ref().expect("a requires import has a sig");
        let _ = writeln!(
            s,
            "                pub fn {}({}){};",
            im.name,
            decl(sig, true),
            ret(sig)
        );
    }
    s.push_str("            }\n\n            /// What an absent module's import calls: the failure value of the API.\n            pub mod absent {\n                #[allow(unused_imports)]\n                use $crate::api::*;\n");
    for (im, sig) in &opt {
        let (Some(a), Some(sig)) = (&im.absent, sig) else {
            continue;
        };
        let body = if a == "void" {
            String::new()
        } else if a == "missing"
            && im
                .service
                .as_ref()
                .is_some_and(|service| im.name == format!("dk_{}_open", service))
        {
            format!(
                " crate::loader::stub_missing({:?}); {missing} as _",
                im.requires.as_deref().unwrap_or("")
            )
        } else if a == "missing" {
            format!(" {missing} as _")
        } else {
            format!(" {a} as _")
        };
        let _ = writeln!(
            s,
            "                pub unsafe extern \"C\" fn {}({}){} {{{body} }}",
            im.name,
            decl(sig, false),
            ret(sig)
        );
    }
    s.push_str("            }\n\n");
    let _ = writeln!(
        s,
        "            /// (name, address from the module or 0, address of the stub or 0, the module that provides it)\n            pub fn table() -> [(&'static str, usize, usize, &'static str); {}] {{\n                [",
        opt.len()
    );
    for (im, _) in &opt {
        let stub = if im.absent.is_some() {
            format!("absent::{} as usize", im.name)
        } else {
            "0".to_string()
        };
        let _ = writeln!(
            s,
            "                    ({:?}, core::hint::black_box({} as usize), {stub}, {:?}),",
            im.name,
            im.name,
            im.requires.as_deref().unwrap_or("")
        );
    }
    s.push_str("                ]\n            }\n        }\n    };\n}\n");
    s
}

/// `sdk/include/dk/gen/imports.h`: the prototypes of the service imports (`[[import]]` with `service`; the ones with `kind = "helper"` keep
/// the prototype of their hand-written header), grouped by service, with the context and the runtime version in the comment.
fn imports_h(sdk: &Sdk) -> Result<String> {
    let imps = imports(sdk)?;
    let mut s = format!(
        "/* {HEADER} */\n/* sdk/include/dk/gen/imports.h -- the service imports of a module (docs/plans/sdk.md section 5.1): one prototype per [[import]] with `service`.\n   Each comment gives the context the call may run in and the runtime version that added it; `patchkit pack` takes the runtime version a module needs from the newest. */\n#ifndef DK_GEN_IMPORTS_H\n#define DK_GEN_IMPORTS_H\n\n#include <stdint.h>\n\n/* Opaque handles ([handle] types): the runtime or the provider module gives one out in `init`. */\n"
    );
    for h in &sdk.handle.types {
        let _ = writeln!(s, "typedef struct {h} {h};");
    }
    s.push_str("\n/* Callback types ([handle.callbacks]): `arg` is the user-data pointer the module gave with the callback. */\n");
    for (n, sig) in callback_types(sdk)? {
        let _ = writeln!(
            s,
            "typedef {};",
            c_decl(&sig.ret, &format!("dk_{n}({})", c_args(&sig)))
        );
    }
    for svc in &sdk.handle.services {
        let own: Vec<_> = imps
            .iter()
            .filter(|(im, sig)| {
                im.service.as_deref() == Some(svc.as_str()) && im.kind.is_none() && sig.is_some()
            })
            .collect();
        if own.is_empty() {
            continue;
        }
        let _ = writeln!(s, "\n/* ---- service {svc} ---- */");
        for (im, sig) in own {
            let sig = sig.as_ref().expect("a service import has a sig");
            let need = match (&im.requires, im.absent.as_deref()) {
                (Some(r), Some(a)) => {
                    let what = match a {
                        "void" => "does nothing".to_string(),
                        "missing" => "returns DK_E_MISSING".to_string(),
                        n => format!("returns {n}"),
                    };
                    format!(" Needs {r}: without it the import binds to a stub that {what}.")
                }
                (Some(r), None) => format!(" Needs {r}: the import is not found without it."),
                _ => String::new(),
            };
            let _ = writeln!(
                s,
                "\n/* {} Context: {}. Since runtime {}.{need} */",
                im.doc,
                im.context.as_deref().unwrap_or_default(),
                im.since.as_deref().unwrap_or_default()
            );
            let _ = writeln!(
                s,
                "{};",
                c_decl(&sig.ret, &format!("{}({})", im.name, c_args(sig)))
            );
        }
    }
    s.push_str("\n#endif /* DK_GEN_IMPORTS_H */\n");
    Ok(s)
}

/// A struct of a typed view as C text.
fn c_struct(s: &mut String, name: &str, comment: &str, fields: &[CField]) {
    let _ = writeln!(s, "/* {comment} */\ntypedef struct {name} {{");
    for CField(t, n, doc) in fields {
        let d = format!("    {};", c_decl(t, n));
        let _ = writeln!(s, "{d:<39} /* {doc} */");
    }
    let _ = writeln!(s, "}} {name};\n");
}

/// A typed C view header: `purpose` line, the include of the consts header, the two structs, the entry points.
fn view_h(
    guard: &str,
    file: &str,
    purpose: &str,
    consts_h: &str,
    structs: [(&str, &str, &[CField]); 2],
    fns: &[(String, Sig, String)],
    c: &CView,
) -> String {
    let mut s = format!("/* {HEADER} */\n/* sdk/include/dk/gen/{file} -- {purpose} */\n");
    if let Some(t) = &c.intro {
        let _ = writeln!(s, "/* {} */", t.trim());
    }
    let _ = write!(
        s,
        "#ifndef {guard}\n#define {guard}\n\n#include <stdint.h>\n#include <dk/gen/{consts_h}>\n\n"
    );
    for (i, (name, comment, fields)) in structs.into_iter().enumerate() {
        let comment = match (&c.desc_doc, i) {
            (Some(d), 1) => d.trim(),
            _ => comment,
        };
        c_struct(&mut s, name, comment, fields);
    }
    if let Some(t) = &c.rules {
        let _ = writeln!(s, "/* {} */\n", t.trim());
    }
    for (name, sig, doc) in fns {
        let _ = writeln!(s, "/* {doc} */");
        let _ = writeln!(
            s,
            "{};\n",
            c_decl(&sig.ret, &format!("{name}({})", c_args(sig)))
        );
    }
    let _ = writeln!(s, "#endif /* {guard} */");
    s
}

