//! The TypeScript file patchkit generates from a `Schema`: the schema constant the page checks values against and the type of the
//! values. It has no imports.

use super::kind::Kind;
use super::schema::Schema;
use super::setting::Setting;
use std::fmt::Write as _;

pub(super) struct TsSchema;

/// A single-quoted TypeScript string literal.
fn quote(text: &str) -> String {
    let mut out = String::from("'");
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            c if (c as u32) < 0x20 || c == '\u{7f}' || c == '\u{2028}' || c == '\u{2029}' => {
                write!(&mut out, "\\u{:04x}", c as u32).unwrap();
            }
            c => out.push(c),
        }
    }
    out.push('\'');
    out
}

/// A property name: bare when it is an identifier, else quoted.
fn property(name: &str) -> String {
    let mut chars = name.chars();
    let bare = chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if bare { name.into() } else { quote(name) }
}

impl TsSchema {
    /// The text of `workbench/gen/settings.ts`.
    pub(super) fn render(schema: &Schema) -> String {
        let mut out = String::from("// Generated by patchkit from workbench.toml. Do not edit.\n");
        writeln!(
            &mut out,
            "export const schema = {{\n  module: {},\n  version: {},\n  settings: [",
            quote(schema.module()),
            schema.descriptor_version()
        )
        .unwrap();
        for setting in schema.settings() {
            writeln!(&mut out, "    {{ {} }},", Self::entry(setting)).unwrap();
        }
        out.push_str("  ],\n} as const;\n\nexport interface Settings {\n");
        for setting in schema.settings() {
            writeln!(
                &mut out,
                "  {}: {};",
                property(setting.id()),
                Self::value_type(setting.kind())
            )
            .unwrap();
        }
        out.push_str("}\n");
        out
    }

    fn entry(setting: &Setting) -> String {
        let mut fields = vec![
            format!("id: {}", quote(setting.id())),
            format!("label: {}", quote(setting.label())),
            format!("kind: {}", quote(setting.kind().name())),
            format!("apply: {}", quote(setting.apply().name())),
        ];
        match setting.kind() {
            Kind::Text { max_bytes } => fields.push(format!("maxBytes: {max_bytes}")),
            Kind::FileName {
                max_bytes,
                extension,
                reset_label,
            } => fields.extend([
                format!("maxBytes: {max_bytes}"),
                format!("extension: {}", quote(extension)),
                format!("resetLabel: {}", quote(reset_label)),
            ]),
            Kind::Integer {
                min,
                max,
                step,
                decimals,
                unit,
                default,
            } => fields.extend([
                format!("min: {min}"),
                format!("max: {max}"),
                format!("step: {step}"),
                format!("decimals: {decimals}"),
                format!("unit: {}", quote(unit)),
                format!("default: {default}"),
            ]),
            Kind::Boolean { default } => fields.push(format!("default: {default}")),
            Kind::Choice { labels, default } => {
                let texts: Vec<String> = labels.iter().map(|l| quote(l.text())).collect();
                fields.extend([
                    format!("choices: [{}]", texts.join(", ")),
                    format!("default: {}", texts[usize::from(*default)]),
                ]);
            }
        }
        fields.join(", ")
    }

    /// The type of a value in `Settings`: an integer is its display value (the stored value divided by 10^decimals).
    fn value_type(kind: &Kind) -> String {
        match kind {
            Kind::Text { .. } | Kind::FileName { .. } => "string | null".into(),
            Kind::Integer { .. } => "number".into(),
            Kind::Boolean { .. } => "boolean".into(),
            Kind::Choice { labels, .. } => labels
                .iter()
                .map(|l| quote(l.text()))
                .collect::<Vec<_>>()
                .join(" | "),
        }
    }
}

