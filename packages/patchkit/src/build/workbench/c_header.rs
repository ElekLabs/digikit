//! The C header patchkit generates from a `Schema`: the descriptor bytes, one key macro per setting and typed inline accessors over
//! `dk_settings_get` and `dk_settings_put`. Names start with `WB_SETTING_` and `wb_setting_`.

use super::kind::Kind;
use super::schema::Schema;
use super::setting::Setting;
use std::fmt::Write as _;

pub(super) struct CHeader {
    text: String,
}

/// An `int32_t` constant expression: negative numbers are parenthesised, the minimum avoids an out-of-range literal.
fn i32_literal(v: i32) -> String {
    match v {
        i32::MIN => "(-2147483647 - 1)".into(),
        v if v < 0 => format!("({v})"),
        v => v.to_string(),
    }
}

impl CHeader {
    /// The text of `workbench_descriptor.h`.
    pub(super) fn render(schema: &Schema) -> String {
        let mut header = CHeader {
            text: String::from(
                "/* Generated by patchkit from module.toml and workbench.toml. */\n\
                #pragma once\n#include <stdint.h>\n#include <dk/gen/imports.h>\n#include <dk/core/status.h>\n",
            ),
        };
        header.descriptor(schema.descriptor());
        for setting in schema.settings() {
            header.setting(setting);
        }
        header.text
    }

    fn descriptor(&mut self, bytes: &[u8]) {
        self.text
            .push_str("static const uint8_t dk_workbench_descriptor[] = {\n");
        for row in bytes.chunks(12) {
            self.text.push_str("    ");
            for byte in row {
                write!(&mut self.text, "0x{byte:02x}, ").unwrap();
            }
            self.text.truncate(self.text.len() - 1);
            self.text.push('\n');
        }
        self.text.push_str("};\n");
    }

    fn define(&mut self, name: String, value: impl std::fmt::Display) {
        writeln!(&mut self.text, "#define {name} {value}").unwrap();
    }

    fn setting(&mut self, s: &Setting) {
        writeln!(&mut self.text, "\n/* {} */", s.label().replace("*/", "* /")).unwrap();
        self.define(s.constant("KEY"), format_args!("\"{}\"", s.id()));
        match s.kind() {
            Kind::Text { max_bytes } | Kind::FileName { max_bytes, .. } => {
                self.define(s.constant("MAX_BYTES"), max_bytes);
            }
            Kind::Integer {
                min,
                max,
                step,
                default,
                ..
            } => {
                self.define(s.constant("MIN"), i32_literal(*min));
                self.define(s.constant("MAX"), i32_literal(*max));
                self.define(s.constant("STEP"), format_args!("{step}u"));
                self.define(s.constant("DEFAULT"), i32_literal(*default));
                self.integer(s);
            }
            Kind::Boolean { default } => {
                self.define(s.constant("DEFAULT"), u8::from(*default));
                self.boolean(s);
            }
            Kind::Choice { labels, default } => {
                self.define(s.constant("COUNT"), labels.len());
                self.define(s.constant("DEFAULT"), default);
                self.text.push_str("enum {\n");
                for (i, label) in labels.iter().enumerate() {
                    writeln!(
                        &mut self.text,
                        "    {} = {i},",
                        s.constant(label.ident().upper())
                    )
                    .unwrap();
                }
                self.text.push_str("};\n");
                self.choice(s);
            }
        }
    }

    fn integer(&mut self, s: &Setting) {
        let (key, min, max, step, default) = (
            s.constant("KEY"),
            s.constant("MIN"),
            s.constant("MAX"),
            s.constant("STEP"),
            s.constant("DEFAULT"),
        );
        let (valid, get, put) = (s.function("valid"), s.function("get"), s.function("put"));
        write!(
            &mut self.text,
            "static inline int {valid}(int32_t v) {{\n\
             \x20   return v >= {min} && v <= {max} && ((uint32_t)v - (uint32_t){min}) % {step} == 0;\n}}\n\
             static inline int32_t {get}(dk_settings *s) {{\n\
             \x20   uint8_t b[4];\n\
             \x20   int32_t v;\n\
             \x20   if (dk_settings_get(s, {key}, b, 4) != 4) return {default};\n\
             \x20   v = (int32_t)(((uint32_t)b[0] << 24) | ((uint32_t)b[1] << 16) | ((uint32_t)b[2] << 8) | (uint32_t)b[3]);\n\
             \x20   return {valid}(v) ? v : {default};\n}}\n\
             static inline int32_t {put}(dk_settings *s, int32_t v) {{\n\
             \x20   uint8_t b[4];\n\
             \x20   if (!{valid}(v)) return DK_E_SET_VALUE;\n\
             \x20   b[0] = (uint8_t)((uint32_t)v >> 24);\n\
             \x20   b[1] = (uint8_t)((uint32_t)v >> 16);\n\
             \x20   b[2] = (uint8_t)((uint32_t)v >> 8);\n\
             \x20   b[3] = (uint8_t)v;\n\
             \x20   return dk_settings_put(s, {key}, b, 4);\n}}\n"
        )
        .unwrap();
    }

    fn boolean(&mut self, s: &Setting) {
        let (key, default) = (s.constant("KEY"), s.constant("DEFAULT"));
        let (valid, get, put) = (s.function("valid"), s.function("get"), s.function("put"));
        write!(
            &mut self.text,
            "static inline int {valid}(int v) {{\n    return v == 0 || v == 1;\n}}\n\
             static inline int {get}(dk_settings *s) {{\n\
             \x20   uint8_t b;\n\
             \x20   if (dk_settings_get(s, {key}, &b, 1) != 1 || b > 1) return {default};\n\
             \x20   return b;\n}}\n\
             static inline int32_t {put}(dk_settings *s, int v) {{\n\
             \x20   uint8_t b = (uint8_t)v;\n\
             \x20   if (!{valid}(v)) return DK_E_SET_VALUE;\n\
             \x20   return dk_settings_put(s, {key}, &b, 1);\n}}\n"
        )
        .unwrap();
    }

    fn choice(&mut self, s: &Setting) {
        let (key, default, count) = (
            s.constant("KEY"),
            s.constant("DEFAULT"),
            s.constant("COUNT"),
        );
        let (valid, get, put) = (s.function("valid"), s.function("get"), s.function("put"));
        write!(
            &mut self.text,
            "static inline int {valid}(uint8_t v) {{\n    return v < {count};\n}}\n\
             static inline uint8_t {get}(dk_settings *s) {{\n\
             \x20   uint8_t b;\n\
             \x20   if (dk_settings_get(s, {key}, &b, 1) != 1 || !{valid}(b)) return {default};\n\
             \x20   return b;\n}}\n\
             static inline int32_t {put}(dk_settings *s, uint8_t v) {{\n\
             \x20   if (!{valid}(v)) return DK_E_SET_VALUE;\n\
             \x20   return dk_settings_put(s, {key}, &v, 1);\n}}\n"
        )
        .unwrap();
    }
}

