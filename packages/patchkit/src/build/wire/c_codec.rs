//! The C header patchkit writes for a `Schema`: per message a struct, `<prefix>_<Msg>_decode`, `<prefix>_<Msg>_encode`, a `_MAX_SIZE`
//! constant (computed here) and, for a message held by another, `_size`. Straight-line code over `<dk/wire.h>`; no libc.
//!
//! Decode skips unknown fields, refuses (returns -1) a string, bytes or repeated field over its bound, a wrong wire type for a known field,
//! truncation, field number 0 and groups. A repeated singular message field replaces the earlier value (protobuf merges them).
//! Encode omits proto3 default values and sets `w->err` for a struct that breaks its own bounds.

mod decode;
mod encode;

use super::schema::{Field, Kind, Scalar, Schema};
use std::fmt::Write as _;

pub struct CCodec<'a> {
    schema: &'a Schema,
    prefix: String,
    out: String,
}

/// Bytes of the varint of `n`.
fn varint_len(n: u64) -> u32 {
    (64 - (n | 1).leading_zeros()).div_ceil(7)
}

fn key_len(f: &Field) -> u32 {
    varint_len(u64::from(f.number) << 3)
}

impl Scalar {
    fn c_type(self) -> &'static str {
        match self {
            Scalar::Uint32 => "uint32_t",
            Scalar::Int32 | Scalar::Enum => "int32_t",
            Scalar::Bool => "uint8_t",
        }
    }

    /// Largest encoded size of one value.
    fn max_size(self) -> u32 {
        match self {
            Scalar::Uint32 => 5,
            Scalar::Int32 | Scalar::Enum => 10,
            Scalar::Bool => 1,
        }
    }
}

impl<'a> CCodec<'a> {
    /// The text of the header; `prefix` starts every name (`pm` gives `pm_Project`).
    pub fn render(schema: &'a Schema, prefix: &str) -> String {
        let mut c = CCodec {
            schema,
            prefix: prefix.to_string(),
            out: String::from(
                "/* Generated by patchkit from a .proto schema. */\n#pragma once\n#include <stdint.h>\n#include <dk/wire.h>\n",
            ),
        };
        for e in &schema.enums {
            c.out.push('\n');
            for (name, number) in &e.values {
                let value = if *number < 0 {
                    format!("({number})")
                } else {
                    number.to_string()
                };
                writeln!(c.out, "#define {}_{} {value}", prefix.to_uppercase(), name).unwrap();
            }
        }
        let max = c.max_sizes();
        for (i, m) in schema.messages.iter().enumerate() {
            writeln!(
                c.out,
                "\n/* {} */\n#define {}_MAX_SIZE {}u",
                m.name,
                c.ty(i),
                max[i]
            )
            .unwrap();
            c.structure(i);
            c.decode(i);
            c.encode(i);
            if m.nested {
                c.size(i);
            }
        }
        c.out
    }

    fn ty(&self, i: usize) -> String {
        format!("{}_{}", self.prefix, self.schema.messages[i].name)
    }

    fn structure(&mut self, i: usize) {
        let ty = self.ty(i);
        writeln!(self.out, "typedef struct {{").unwrap();
        for f in &self.schema.messages[i].fields {
            let n = &f.name;
            let line = match (&f.kind, f.repeated) {
                (Kind::Scalar(s), None) => format!("{} {n};", s.c_type()),
                (Kind::Scalar(s), Some(max)) => {
                    format!("{} {n}[{max}];\n    uint32_t {n}_count;", s.c_type())
                }
                (Kind::String(max), None) => {
                    format!("char {n}[{}];\n    uint32_t {n}_len;", max + 1)
                }
                (Kind::Bytes(max), None) => format!("uint8_t {n}[{max}];\n    uint32_t {n}_len;"),
                (Kind::String(max), Some(count)) => format!(
                    "char {n}[{count}][{}];\n    uint32_t {n}_len[{count}];\n    uint32_t {n}_count;",
                    max + 1
                ),
                (Kind::Message(m), None) => format!("{} {n};\n    uint8_t has_{n};", self.ty(*m)),
                (Kind::Message(m), Some(max)) => {
                    format!("{} {n}[{max}];\n    uint32_t {n}_count;", self.ty(*m))
                }
                (Kind::Bytes(_), Some(_)) => unreachable!("refused by the schema"),
            };
            writeln!(self.out, "    {line}").unwrap();
        }
        writeln!(self.out, "}} {ty};\n").unwrap();
    }

    /// The most bytes of one message, by message index (a message comes after the messages it holds).
    fn max_sizes(&self) -> Vec<u32> {
        let mut max: Vec<u32> = vec![];
        for m in &self.schema.messages {
            let mut total = 0;
            for f in &m.fields {
                let key = key_len(f);
                let one = |kind: &Kind| match kind {
                    Kind::Scalar(s) => s.max_size(),
                    Kind::String(n) | Kind::Bytes(n) => varint_len(u64::from(*n)) + n,
                    Kind::Message(i) => varint_len(u64::from(max[*i])) + max[*i],
                };
                total += match (&f.kind, f.repeated) {
                    (Kind::Scalar(s), Some(n)) => {
                        let body = n * s.max_size();
                        key + varint_len(u64::from(body)) + body
                    }
                    (kind, Some(n)) => n * (key + one(kind)),
                    (kind, None) => key + one(kind),
                };
            }
            max.push(total);
        }
        max
    }
}

