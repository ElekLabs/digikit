//! The C that patchkit writes for a `Schema`. The header holds the enums, per message a struct and a `_MAX_SIZE` constant (computed
//! here) and, for a service, the handler prototypes and the query table. The source holds per message `<prefix>_<Msg>_decode`,
//! `<prefix>_<Msg>_encode` and, for a message held by another, `_size`, then the call functions and the table. Straight-line code over
//! `<dk/wire.h>` (the helpers are the SDK component `sdk/src/wire/wire.c`); no libc.
//!
//! Decode skips unknown fields, refuses (returns -1) a string, bytes or repeated field over its bound, a wrong wire type for a known field,
//! truncation, field number 0, groups and a singular message field that occurs twice (protobuf merges them; the decoder does not).
//! Encode omits proto3 default values and sets `w->err` for a struct that breaks its own bounds.

mod call;
mod decode;
mod encode;
mod size;

pub(super) use size::{max_sizes, struct_sizes};

use super::schema::{Kind, Scalar, Schema};
use std::fmt::Write as _;

/// The two files of a schema.
pub struct Generated {
    pub header: String,
    pub source: String,
}

pub struct CCodec<'a> {
    schema: &'a Schema,
    prefix: String,
    /// The header text.
    head: String,
    /// The source text.
    out: String,
}

impl Scalar {
    fn c_type(self) -> &'static str {
        match self {
            Scalar::Uint32 => "uint32_t",
            Scalar::Int32 | Scalar::Enum => "int32_t",
            Scalar::Bool => "uint8_t",
        }
    }
}

impl<'a> CCodec<'a> {
    /// The header and the source; `prefix` starts every name (`pm` gives `pm_Project`), `header_name` is the file name the source includes.
    pub fn render(schema: &'a Schema, prefix: &str, header_name: &str) -> Generated {
        let mut c = CCodec {
            schema,
            prefix: prefix.to_string(),
            head: String::from(
                "/* Generated by patchkit from a .proto schema. Do not edit. */\n#pragma once\n#include <stdint.h>\n",
            ),
            out: format!(
                "/* Generated by patchkit from a .proto schema. Do not edit. */\n#include <stdint.h>\n#include <dk/core/status.h>\n#include <dk/wire.h>\n#include \"{header_name}\"\n"
            ),
        };
        if schema.service.is_some() {
            c.head
                .push_str("#include <dk/gen/imports.h>\n#include <dk/query.h>\n");
        }
        for e in &schema.enums {
            c.head.push('\n');
            for (name, number) in &e.values {
                // the enum's name keeps equal value names of nested enums apart
                let value = if *number < 0 {
                    format!("({number})")
                } else {
                    number.to_string()
                };
                writeln!(
                    c.head,
                    "#define {}_{}_{} {value}",
                    prefix.to_uppercase(),
                    e.name,
                    name
                )
                .unwrap();
            }
        }
        let max = size::max_sizes(schema);
        for (i, m) in schema.messages.iter().enumerate() {
            writeln!(
                c.head,
                "\n/* {} */\n#define {}_MAX_SIZE {}u",
                m.name,
                c.ty(i),
                max[i]
            )
            .unwrap();
            c.structure(i);
            c.decode(i);
            c.encode(i);
            if m.nested {
                c.size(i);
            }
        }
        c.service();
        Generated {
            header: c.head,
            source: c.out,
        }
    }

    fn ty(&self, i: usize) -> String {
        format!("{}_{}", self.prefix, self.schema.messages[i].name)
    }

    fn structure(&mut self, i: usize) {
        let ty = self.ty(i);
        writeln!(self.head, "typedef struct {{").unwrap();
        for f in &self.schema.messages[i].fields {
            let n = &f.name;
            let line = match (&f.kind, f.repeated) {
                (Kind::Scalar(s), None) => format!("{} {n};", s.c_type()),
                (Kind::Scalar(s), Some(max)) => {
                    format!("{} {n}[{max}];\n    uint32_t {n}_count;", s.c_type())
                }
                (Kind::String(max), None) => {
                    format!(
                        "char {n}[{}];\n    uint32_t {n}_len;",
                        max.saturating_add(1)
                    )
                }
                (Kind::Bytes(max), None) => format!("uint8_t {n}[{max}];\n    uint32_t {n}_len;"),
                (Kind::String(max), Some(count)) => format!(
                    "char {n}[{count}][{}];\n    uint32_t {n}_len[{count}];\n    uint32_t {n}_count;",
                    max.saturating_add(1)
                ),
                (Kind::Message(m), None) => format!("{} {n};\n    uint8_t has_{n};", self.ty(*m)),
                (Kind::Message(m), Some(max)) => {
                    format!("{} {n}[{max}];\n    uint32_t {n}_count;", self.ty(*m))
                }
                (Kind::Bytes(_), Some(_)) => unreachable!("refused by the schema"),
            };
            writeln!(self.head, "    {line}").unwrap();
        }
        writeln!(self.head, "}} {ty};").unwrap();
    }
}
