//! `cfaot`: translate hot ColdFire functions to Rust (the native kernels of `src/cpu/native.rs`).
//!
//! usage: cfaot DATA.toml IMAGE OUT_DIR
//!
//! DATA.toml (a file of `devices/cf-native/`) names the image by its SHA-256 and gives its load address and the entries of the
//! functions to translate. IMAGE is the firmware section the data file describes; its hash must match. The tool decodes each function
//! with the interpreter's own decoder, follows its control flow (calls and indirect jumps are refused), and writes
//! `OUT_DIR/kernels.rs` and `OUT_DIR/PROVENANCE.txt`. The generated code holds no firmware bytes: only the entry, the length, the
//! FNV-1a hash of the code, the instruction offsets, and Rust that does what each instruction does. The build reads it through
//! `CF_NATIVE_DIR=OUT_DIR` (`coldfire/build.rs`), and it stays under out/.
//!
//! Exactness. Forms the translator knows are written out with the interpreter's own arithmetic helpers (flags, MAC, shifts); every
//! other form calls the interpreter for that one instruction (`native_exec`). CCR writes that no later instruction reads before
//! another full write are dropped (liveness over the function's flow graph; the flags are live at every exit). A memory access that
//! fails stops the kernel before the instruction, so the interpreter takes the fault itself.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use coldfire::cpu::native::fnv1a;
use coldfire::{Ea, Form, Insn, Operand, Size, decode_at};

const X: u8 = 0x10;
const N: u8 = 0x08;
const Z: u8 = 0x04;
const V: u8 = 0x02;
const C: u8 = 0x01;
const ALL: u8 = X | N | Z | V | C;
const NZVC: u8 = N | Z | V | C;

fn main() {
    let args: Vec<String> = std::env::args().collect();
    if args.len() != 4 {
        eprintln!("usage: cfaot DATA.toml IMAGE OUT_DIR");
        std::process::exit(2);
    }
    let data = Data::parse(&std::fs::read_to_string(&args[1]).expect("read data file"));
    let image = std::fs::read(&args[2]).expect("read image");
    let sha = sha256_hex(&image);
    if sha != data.image_sha256 {
        eprintln!(
            "cfaot: image sha256 {sha} is not the data file's {}",
            data.image_sha256
        );
        std::process::exit(1);
    }
    let mut out = String::new();
    let mut prov = String::new();
    writeln!(
        out,
        "// Generated by cfaot from {} (never edit, never commit: firmware-derived).",
        args[1]
    )
    .unwrap();
    writeln!(
        prov,
        "cfaot native kernels\ndata: {}\nimage sha256: {sha}\nimage bytes: {}\nbase: {:#x}",
        args[1],
        image.len(),
        data.base
    )
    .unwrap();
    let mut funcs = Vec::new();
    for &entry in &data.functions {
        let f = Func::build(&image, data.base, entry).unwrap_or_else(|e| {
            eprintln!("cfaot: function {entry:#x}: {e}");
            std::process::exit(1);
        });
        writeln!(
            prov,
            "function {entry:#x}: {} bytes, {} instructions, {} generic",
            f.len,
            f.insns.len(),
            f.generic
        )
        .unwrap();
        funcs.push(f);
    }
    // KERNELS table
    writeln!(out, "pub static KERNELS: &[KernelDesc] = &[").unwrap();
    for f in &funcs {
        let offs: Vec<String> = f.insns.keys().map(|a| (a - f.entry).to_string()).collect();
        writeln!(
            out,
            "    KernelDesc {{ entry: {:#x}, len: {}, hash: {:#x}, insns: &[{}] }},",
            f.entry,
            f.len,
            f.hash,
            offs.join(", ")
        )
        .unwrap();
    }
    writeln!(out, "];\n").unwrap();
    writeln!(out, "fn run<B: Bus>(id: usize, c: &mut Cpu, bus: &mut B, ins: &[Insn], budget: u64) -> u64 {{\n    match id {{").unwrap();
    for (k, _) in funcs.iter().enumerate() {
        writeln!(out, "        {k} => kernel_{k}(c, bus, ins, budget),").unwrap();
    }
    writeln!(out, "        _ => unreachable!(),\n    }}\n}}\n").unwrap();
    for (k, f) in funcs.iter().enumerate() {
        out.push_str(&f.emit(k));
    }
    let dir = std::path::Path::new(&args[3]);
    std::fs::create_dir_all(dir).expect("create out dir");
    std::fs::write(dir.join("kernels.rs"), out).expect("write kernels.rs");
    std::fs::write(dir.join("PROVENANCE.txt"), prov).expect("write PROVENANCE.txt");
}

// ---------------------------------------------------------------------------------------------------------------------------------
// The data file: `key = value` lines, `#` comments, `functions = [..]` on one or more lines.

struct Data {
    image_sha256: String,
    base: u32,
    functions: Vec<u32>,
}

impl Data {
    fn parse(text: &str) -> Data {
        let mut sha = String::new();
        let mut base = None;
        let mut functions = Vec::new();
        let mut in_list = false;
        for raw in text.lines() {
            let line = raw.split('#').next().unwrap().trim();
            let num = |s: &str| {
                let s = s.trim().trim_end_matches(',');
                u32::from_str_radix(s.trim_start_matches("0x"), 16).expect("hex number")
            };
            if in_list {
                for t in line
                    .trim_end_matches(']')
                    .split(',')
                    .filter(|t| !t.trim().is_empty())
                {
                    functions.push(num(t));
                }
                in_list = !line.contains(']');
            } else if let Some((k, v)) = line.split_once('=') {
                let (k, v) = (k.trim(), v.trim());
                match k {
                    "image_sha256" => sha = v.trim_matches('"').to_string(),
                    "base" => base = Some(num(v)),
                    "functions" => {
                        let body = v.trim_start_matches('[');
                        for t in body
                            .trim_end_matches(']')
                            .split(',')
                            .filter(|t| !t.trim().is_empty())
                        {
                            functions.push(num(t));
                        }
                        in_list = !v.contains(']');
                    }
                    _ => {}
                }
            }
        }
        Data {
            image_sha256: sha,
            base: base.expect("data file has no base"),
            functions,
        }
    }
}

// ---------------------------------------------------------------------------------------------------------------------------------
// A function: its instructions and flow.

struct Func {
    entry: u32,
    len: u32,
    hash: u64,
    insns: BTreeMap<u32, Insn>,
    leaders: BTreeSet<u32>,
    live_out: BTreeMap<u32, u8>,
    generic: usize,
}

fn target(i: &Insn) -> u32 {
    match i.operands().first() {
        Some(Operand::Target(t)) => *t,
        _ => panic!("branch without target"),
    }
}

fn cond_uses(cc: u8) -> u8 {
    match cc {
        0 | 1 => 0,
        2 | 3 => C | Z,
        4 | 5 => C,
        6 | 7 => Z,
        8 | 9 => V,
        10 | 11 => N,
        12 | 13 => N | V,
        _ => Z | N | V,
    }
}

impl Func {
    fn build(image: &[u8], base: u32, entry: u32) -> Result<Func, String> {
        let at = |a: u32| decode_at(image, base, (a - base) as usize);
        let mut insns = BTreeMap::new();
        let mut leaders = BTreeSet::from([entry]);
        let mut work = vec![entry];
        while let Some(mut a) = work.pop() {
            loop {
                if insns.contains_key(&a) {
                    break;
                }
                if a < base || a >= base + image.len() as u32 {
                    return Err(format!("flow leaves the image at {a:#x}"));
                }
                let i = at(a).ok_or(format!("undecodable at {a:#x}"))?;
                let next = a + u32::from(i.len);
                insns.insert(a, i);
                match i.form {
                    Form::Rts => break,
                    Form::Bra => {
                        let t = target(&i);
                        leaders.insert(t);
                        work.push(t);
                        break;
                    }
                    Form::Bcc => {
                        let t = target(&i);
                        leaders.insert(t);
                        leaders.insert(next);
                        work.push(t);
                    }
                    Form::Bsr
                    | Form::Jsr
                    | Form::Jmp
                    | Form::Rte
                    | Form::Trap
                    | Form::Stop
                    | Form::Halt => {
                        return Err(format!("unsupported flow {:?} at {a:#x}", i.form));
                    }
                    _ => {}
                }
                a = next;
            }
        }
        let end = insns
            .iter()
            .map(|(a, i)| a + u32::from(i.len))
            .max()
            .unwrap();
        let first = *insns.keys().next().unwrap();
        if first != entry {
            return Err("a branch targets before the entry".into());
        }
        let len = end - entry;
        let o = (entry - base) as usize;
        let hash = fnv1a(&image[o..o + len as usize]);
        let mut f = Func {
            entry,
            len,
            hash,
            insns,
            leaders,
            live_out: BTreeMap::new(),
            generic: 0,
        };
        f.liveness();
        f.generic = f.insns.values().filter(|i| spec_info(i).is_none()).count();
        Ok(f)
    }

    /// Backward flag liveness; the flags are live at every exit.
    fn liveness(&mut self) {
        let addrs: Vec<u32> = self.insns.keys().copied().collect();
        let mut live_in: BTreeMap<u32, u8> = addrs.iter().map(|&a| (a, 0)).collect();
        let mut live_out: BTreeMap<u32, u8> = addrs.iter().map(|&a| (a, 0)).collect();
        loop {
            let mut changed = false;
            for &a in addrs.iter().rev() {
                let i = self.insns[&a];
                let next = a + u32::from(i.len);
                let succ_in = |t: u32| live_in.get(&t).copied().unwrap_or(0);
                let out = match i.form {
                    Form::Rts => ALL,
                    Form::Bra => succ_in(target(&i)),
                    Form::Bcc => succ_in(target(&i)) | succ_in(next),
                    _ => succ_in(next),
                };
                let mut info = flag_info(&i);
                // A kernel can stop before this instruction (a failed access, the budget at a block start): the interpreter then
                // continues from `a` and must find the flags exactly as it would have left them.
                if self.leaders.contains(&a) {
                    info.uses = ALL;
                }
                let inn = (out & !info.kill) | info.uses;
                if out != live_out[&a] || inn != live_in[&a] {
                    changed = true;
                    live_out.insert(a, out);
                    live_in.insert(a, inn);
                }
            }
            if !changed {
                break;
            }
        }
        self.live_out = live_out;
    }

    fn emit(&self, k: usize) -> String {
        let idx: BTreeMap<u32, usize> = self
            .insns
            .keys()
            .enumerate()
            .map(|(n, a)| (*a, n))
            .collect();
        let mut s = String::new();
        writeln!(
            s,
            "#[allow(unused_mut, unused_assignments, unused_variables, unused_parens, clippy::all)]"
        )
        .unwrap();
        writeln!(
            s,
            "fn kernel_{k}<B: Bus>(c: &mut Cpu, bus: &mut B, ins: &[Insn], budget: u64) -> u64 {{"
        )
        .unwrap();
        writeln!(s, "    let icount0 = c.icount;\n    let mut tot: u64 = 0;\n    let mut committed: u64 = 0;").unwrap();
        writeln!(s, "    macro_rules! exit {{ ($pc:expr) => {{{{ c.pc = $pc; c.icount += tot - committed; return c.icount - icount0; }}}} }}").unwrap();
        writeln!(
            s,
            "    let mut pc: u32 = {:#x};\n    loop {{\n        match pc {{",
            self.entry
        )
        .unwrap();
        // blocks
        let leaders: Vec<u32> = self.leaders.iter().copied().collect();
        for &l in &leaders {
            let mut block = Vec::new();
            let mut a = l;
            loop {
                let i = self.insns[&a];
                block.push(a);
                let next = a + u32::from(i.len);
                if matches!(i.form, Form::Rts | Form::Bra | Form::Bcc)
                    || self.leaders.contains(&next)
                    || !self.insns.contains_key(&next)
                {
                    break;
                }
                a = next;
            }
            writeln!(s, "            {l:#x} => {{").unwrap();
            writeln!(
                s,
                "                if tot + {} > budget {{ exit!({l:#x}); }}",
                block.len()
            )
            .unwrap();
            let last = *block.last().unwrap();
            for &a in &block {
                let i = self.insns[&a];
                let next = a + u32::from(i.len);
                let fl = self.live_out[&a];
                let lines = emit_insn(&i, a, next, fl, idx[&a]);
                for line in lines {
                    writeln!(s, "                {line}").unwrap();
                }
            }
            let i = self.insns[&last];
            // Every block but one that ends in a return or an unconditional branch goes on at the next instruction.
            if !matches!(i.form, Form::Rts | Form::Bra) {
                writeln!(s, "                pc = {:#x};", last + u32::from(i.len)).unwrap();
            }
            writeln!(s, "            }}").unwrap();
        }
        writeln!(
            s,
            "            _ => unreachable!(\"kernel {k}: pc {{pc:#x}}\"),\n        }}\n    }}\n}}\n"
        )
        .unwrap();
        s
    }
}

// ---------------------------------------------------------------------------------------------------------------------------------
// Per instruction.

struct FlagInfo {
    /// Flags the instruction reads.
    uses: u8,
    /// Flags it overwrites completely.
    kill: u8,
}

fn flag_info(i: &Insn) -> FlagInfo {
    let known = spec_info(i).is_some();
    let kill = match i.form {
        _ if !known => 0,
        Form::Moveq | Form::Move | Form::Andi | Form::Ori | Form::Eori | Form::Cmp | Form::Cmpi => {
            NZVC
        }
        Form::AddToD | Form::SubToD | Form::Addi | Form::Subi => ALL,
        Form::Addq | Form::Subq => match i.operands().get(1) {
            Some(Operand::Ea(Ea::An(_))) => 0,
            _ => ALL,
        },
        Form::AsrI
        | Form::AslI
        | Form::LsrI
        | Form::LslI
        | Form::AsrR
        | Form::AslR
        | Form::LsrR
        | Form::LslR => NZVC,
        _ => 0,
    };
    let may_stop =
        emit_spec(i, 0, 0, ALL, 0).is_some_and(|l| l.iter().any(|s| s.contains("exit!(")));
    let uses = match i.form {
        _ if !known || may_stop => ALL,
        Form::Bcc => cond_uses(i.cond),
        _ => 0,
    };
    FlagInfo { uses, kill }
}

fn ea_of(i: &Insn, k: usize) -> Ea {
    match i.operands().get(k) {
        Some(Operand::Ea(e)) => *e,
        other => panic!("operand {k} of {:?} is {other:?}", i.form),
    }
}

fn imm_of(i: &Insn, k: usize) -> u32 {
    match i.operands().get(k) {
        Some(Operand::Imm(v)) => *v,
        other => panic!("operand {k} of {:?} is {other:?}", i.form),
    }
}

/// A memory address: a statement list that defines `ad`, and the register update to apply after the access succeeded.
struct Mem {
    ad: String,
    post: Option<String>,
}

fn reg(r: u8) -> String {
    if r < 8 {
        format!("c.d[{r}]")
    } else {
        format!("c.a[{}]", r - 8)
    }
}

fn mem_of(ea: &Ea) -> Option<Mem> {
    Some(match *ea {
        Ea::Ind(r) => Mem {
            ad: format!("c.a[{r}]"),
            post: None,
        },
        Ea::Post(r) => Mem {
            ad: format!("c.a[{r}]"),
            post: Some(format!("c.a[{r}] = ad.wrapping_add(4);")),
        },
        Ea::Pre(r) => Mem {
            ad: format!("c.a[{r}].wrapping_sub(4)"),
            post: Some(format!("c.a[{r}] = ad;")),
        },
        Ea::Disp(r, d) => Mem {
            ad: format!("c.a[{r}].wrapping_add({:#x})", d as i32 as u32),
            post: None,
        },
        Ea::Idx {
            an,
            xn,
            wl,
            scale,
            d8,
        } if wl && scale < 3 => Mem {
            ad: format!(
                "c.a[{an}].wrapping_add({}.wrapping_shl({scale})).wrapping_add({:#x})",
                reg(xn),
                d8 as i32 as u32
            ),
            post: None,
        },
        Ea::AbsW(v) => Mem {
            ad: format!("{:#x}", v as i32 as u32),
            post: None,
        },
        Ea::AbsL(v) => Mem {
            ad: format!("{v:#x}"),
            post: None,
        },
        Ea::PcDisp { base, d16 } => Mem {
            ad: format!("{:#x}", base.wrapping_add(d16 as i32 as u32)),
            post: None,
        },
        _ => return None,
    })
}

/// Whether a form is written out. The same decision `emit_insn` makes, without producing text.
fn spec_info(i: &Insn) -> Option<()> {
    let probe = emit_spec(i, 0, 0, ALL, 0)?;
    drop(probe);
    Some(())
}

fn emit_insn(i: &Insn, pc: u32, next: u32, fl: u8, idx: usize) -> Vec<String> {
    match emit_spec(i, pc, next, fl, idx) {
        Some(lines) => lines,
        None => vec![
            "c.icount += tot - committed; committed = tot;".into(),
            format!(
                "match c.native_exec(bus, &ins[{idx}], {pc:#x}) {{ Ok(true) => {{ tot += 1; committed += 1; }} Ok(false) => {{ return c.icount - icount0; }} Err(s) => {{ c.native.stop = Some(s); return c.icount - icount0; }} }}"
            ),
            format!("if c.native_code_written() {{ exit!({next:#x}); }}"),
        ],
    }
}

/// The text of a written-out form, or None (the interpreter runs it). `fl` is the set of flags live after the instruction.
fn emit_spec(i: &Insn, pc: u32, next: u32, fl: u8, _idx: usize) -> Option<Vec<String>> {
    let mut o: Vec<String> = Vec::new();
    let bail = format!("exit!({pc:#x})");
    let info_writes = {
        // flag writes this instruction would make, intersected with what is live
        let w = match i.form {
            Form::Moveq
            | Form::Move
            | Form::Andi
            | Form::Ori
            | Form::Eori
            | Form::Cmp
            | Form::Cmpi => NZVC,
            Form::AddToD | Form::SubToD | Form::Addi | Form::Subi => ALL,
            Form::Addq | Form::Subq => match i.operands().get(1) {
                Some(Operand::Ea(Ea::An(_))) => 0,
                _ => ALL,
            },
            Form::AsrI
            | Form::AslI
            | Form::LsrI
            | Form::LslI
            | Form::AsrR
            | Form::AslR
            | Form::LsrR
            | Form::LslR => ALL,
            _ => 0,
        };
        w & fl != 0
    };
    let mut wrote_mem = false;
    // Read a longword source operand into `v`.
    let read_src = |o: &mut Vec<String>, ea: &Ea| -> Option<()> {
        match *ea {
            Ea::Dn(r) => o.push(format!("let v = c.d[{r}];")),
            Ea::An(r) => o.push(format!("let v = c.a[{r}];")),
            Ea::Imm(v) => o.push(format!("let v = {v:#x}u32;")),
            _ => {
                let m = mem_of(ea)?;
                o.push(format!("let ad = {};", m.ad));
                o.push(format!(
                    "let v = match bus.read32(ad) {{ Ok(v) => v, Err(_) => {bail} }};"
                ));
                if let Some(p) = m.post {
                    o.push(p);
                }
            }
        }
        Some(())
    };
    match i.form {
        Form::Moveq => {
            let Ea::Dn(r) = ea_of(i, 1) else { return None };
            let v = imm_of(i, 0);
            o.push(format!("c.d[{r}] = {v:#x};"));
            if info_writes {
                o.push(format!("c.native_set_nz({v:#x});"));
            }
        }
        Form::Move if i.size == Size::L => {
            let (src, dst) = (ea_of(i, 0), ea_of(i, 1));
            // two memory operands with a register update on the source: the interpreter runs it
            if mem_of(&src).is_some_and(|m| m.post.is_some()) && !matches!(dst, Ea::Dn(_)) {
                return None;
            }
            read_src(&mut o, &src)?;
            match dst {
                Ea::Dn(r) => o.push(format!("c.d[{r}] = v;")),
                Ea::An(_) | Ea::Imm(_) | Ea::PcDisp { .. } | Ea::PcIdx { .. } => return None,
                _ => {
                    let m = mem_of(&dst)?;
                    o.push(format!("let ad = {};", m.ad));
                    o.push(format!(
                        "if c.native_write32(bus, ad, v).is_err() {{ {bail} }}"
                    ));
                    if let Some(p) = m.post {
                        o.push(p);
                    }
                    wrote_mem = true;
                }
            }
            if info_writes {
                o.push("c.native_set_nz(v);".into());
            }
        }
        Form::Movea if i.size == Size::L => {
            let Ea::An(r) = ea_of(i, 1) else { return None };
            read_src(&mut o, &ea_of(i, 0))?;
            o.push(format!("c.a[{r}] = v;"));
        }
        Form::Lea => {
            let Ea::An(r) = ea_of(i, 1) else { return None };
            let m = mem_of(&ea_of(i, 0))?;
            if m.post.is_some() {
                return None;
            }
            o.push(format!("c.a[{r}] = {};", m.ad));
        }
        Form::AddToD | Form::SubToD => {
            let Ea::Dn(r) = ea_of(i, 1) else { return None };
            read_src(&mut o, &ea_of(i, 0))?;
            let add = i.form == Form::AddToD;
            o.push(format!("let d = c.d[{r}];"));
            o.push(format!(
                "let r = d.wrapping_{}(v);",
                if add { "add" } else { "sub" }
            ));
            o.push(format!("c.d[{r}] = r;"));
            if info_writes {
                o.push(format!(
                    "c.native_flags_{}(v, d, r{});",
                    if add { "add" } else { "sub" },
                    if add { "" } else { ", false" }
                ));
            }
        }
        Form::Adda | Form::Suba if i.size == Size::L => {
            let Ea::An(r) = ea_of(i, 1) else { return None };
            read_src(&mut o, &ea_of(i, 0))?;
            o.push(format!(
                "c.a[{r}] = c.a[{r}].wrapping_{}(v);",
                if i.form == Form::Adda { "add" } else { "sub" }
            ));
        }
        Form::Addq | Form::Subq => {
            let q = imm_of(i, 0);
            let add = i.form == Form::Addq;
            match ea_of(i, 1) {
                Ea::An(r) => o.push(format!(
                    "c.a[{r}] = c.a[{r}].wrapping_{}({q:#x});",
                    if add { "add" } else { "sub" }
                )),
                Ea::Dn(r) => {
                    o.push(format!("let d = c.d[{r}];"));
                    o.push(format!(
                        "let r = d.wrapping_{}({q:#x});",
                        if add { "add" } else { "sub" }
                    ));
                    o.push(format!("c.d[{r}] = r;"));
                    if info_writes {
                        o.push(format!(
                            "c.native_flags_{}({q:#x}, d, r{});",
                            if add { "add" } else { "sub" },
                            if add { "" } else { ", false" }
                        ));
                    }
                }
                _ => return None,
            }
        }
        Form::Andi | Form::Ori | Form::Eori | Form::Addi | Form::Subi => {
            let Ea::Dn(r) = ea_of(i, 1) else { return None };
            let v = imm_of(i, 0);
            o.push(format!("let d = c.d[{r}];"));
            let (expr, flags) = match i.form {
                Form::Andi => (format!("d & {v:#x}"), "c.native_set_nz(r);".to_string()),
                Form::Ori => (format!("d | {v:#x}"), "c.native_set_nz(r);".to_string()),
                Form::Eori => (format!("d ^ {v:#x}"), "c.native_set_nz(r);".to_string()),
                Form::Addi => (
                    format!("d.wrapping_add({v:#x})"),
                    format!("c.native_flags_add({v:#x}, d, r);"),
                ),
                _ => (
                    format!("d.wrapping_sub({v:#x})"),
                    format!("c.native_flags_sub({v:#x}, d, r, false);"),
                ),
            };
            o.push(format!("let r = {expr};"));
            o.push(format!("c.d[{r}] = r;", r = r));
            if info_writes {
                o.push(flags);
            }
        }
        Form::Cmp if i.size == Size::L => {
            let Ea::Dn(r) = ea_of(i, 1) else { return None };
            read_src(&mut o, &ea_of(i, 0))?;
            if info_writes {
                o.push(format!("let d = c.d[{r}];"));
                o.push("c.native_flags_sub(v, d, d.wrapping_sub(v), true);".into());
            }
        }
        Form::AsrI
        | Form::AslI
        | Form::LsrI
        | Form::LslI
        | Form::AsrR
        | Form::AslR
        | Form::LsrR
        | Form::LslR => {
            let left = matches!(i.form, Form::AslI | Form::LslI | Form::AslR | Form::LslR);
            let arith = matches!(i.form, Form::AsrI | Form::AslI | Form::AsrR | Form::AslR);
            let (count, dst) = match i.form {
                Form::AsrI | Form::AslI | Form::LsrI | Form::LslI => {
                    let Ea::Dn(r) = ea_of(i, 1) else { return None };
                    (format!("{}u32", imm_of(i, 0) & 63), r)
                }
                _ => {
                    let (Ea::Dn(y), Ea::Dn(r)) = (ea_of(i, 0), ea_of(i, 1)) else {
                        return None;
                    };
                    (format!("(c.d[{y}] & 63)"), r)
                }
            };
            o.push(format!("let count = {count};"));
            if info_writes {
                o.push(format!(
                    "c.d[{dst}] = c.native_shift_flags(c.d[{dst}], count, {left}, {arith});"
                ));
            } else {
                o.push(format!(
                    "c.d[{dst}] = Cpu::native_shift_l(c.d[{dst}], count, {left}, {arith});"
                ));
            }
        }
        Form::Mac | Form::Msac | Form::MacLoad | Form::MsacLoad => {
            let word = i.size == Size::W;
            let (ry, uy) = i.mac_ry();
            let (rx, ux) = i.mac_rx();
            let sel = |r: u8, up: bool| {
                let v = reg(r);
                if !word {
                    v
                } else if up {
                    format!("({v} >> 16)")
                } else {
                    format!("({v} & 0xffff)")
                }
            };
            o.push(format!("let ry = {};", sel(ry, uy)));
            o.push(format!("let rx = {};", sel(rx, ux)));
            let sub = matches!(i.form, Form::Msac | Form::MsacLoad);
            if matches!(i.form, Form::MacLoad | Form::MsacLoad) {
                let m = mem_of(&ea_of(i, 3))?;
                let rw = match ea_of(i, 5) {
                    Ea::Dn(r) => format!("c.d[{r}]"),
                    Ea::An(r) => format!("c.a[{r}]"),
                    _ => return None,
                };
                o.push(format!("let ad = {};", m.ad));
                let addr = if i.mac_mask() {
                    "ad & c.native_mask()"
                } else {
                    "ad"
                };
                o.push(format!(
                    "let loaded = match bus.read32({addr}) {{ Ok(v) => v, Err(_) => {bail} }};"
                ));
                if let Some(p) = m.post {
                    o.push(p);
                }
                o.push(format!("{rw} = loaded;"));
            }
            o.push(format!(
                "c.native_mac(ry, rx, {word}, {}, {}, {sub});",
                i.mac_scale(),
                i.mac_acc()
            ));
        }
        Form::Movclr => {
            let Some(Operand::Acc(a)) = i.operands().first().copied() else {
                return None;
            };
            let dst = match ea_of(i, 1) {
                Ea::Dn(r) => format!("c.d[{r}]"),
                Ea::An(r) => format!("c.a[{r}]"),
                _ => return None,
            };
            o.push(format!("{dst} = c.native_movclr({a});"));
        }
        Form::MoveToAcc => {
            let Some(Operand::Acc(a)) = i.operands().get(1).copied() else {
                return None;
            };
            read_src(&mut o, &ea_of(i, 0))?;
            o.push(format!("c.native_move_to_acc({a}, v);"));
        }
        Form::MoveFromAcc => {
            let Some(Operand::Acc(a)) = i.operands().first().copied() else {
                return None;
            };
            let Ea::Dn(r) = ea_of(i, 1) else { return None };
            o.push(format!("c.d[{r}] = c.native_acc_to_reg({a});"));
        }
        Form::Bcc | Form::Bra => {
            let t = target(i);
            o.push("tot += 1;".into());
            if i.form == Form::Bra {
                o.push(format!("pc = {t:#x};"));
                o.push("continue;".into());
            } else {
                o.push(format!(
                    "if c.native_cond({}) {{ pc = {t:#x}; continue; }}",
                    i.cond
                ));
            }
            return Some(o);
        }
        Form::Rts => {
            o.push(
                "let ret = match bus.read32(c.a[7]) { Ok(v) => v, Err(_) => ".to_string()
                    + &bail
                    + " };",
            );
            o.push("c.a[7] = c.a[7].wrapping_add(4);".into());
            o.push("tot += 1;".into());
            o.push("exit!(ret);".into());
            return Some(o);
        }
        _ => return None,
    }
    o.push("tot += 1;".into());
    if wrote_mem {
        o.push(format!(
            "if c.native_code_written() {{ exit!({next:#x}); }}"
        ));
    }
    // Statements that define `v`, `ad`, `d`, `r` are scoped to the instruction.
    let mut wrapped = vec!["{".to_string()];
    wrapped.extend(o);
    wrapped.push("}".into());
    Some(wrapped)
}

